-- ============================================================
-- 目录/标签/正文 三分判据（2026-10-07）
--
-- ## 为什么改成三分
--
-- 前面几轮都是二分（目录 vs 标签），踩到两件事：
--
--   1. 我说「泛型」该是标签（按"要不要单独学一遍"判的）——**用户纠正：泛型能单独学，
--      有一整套（协变/逆变/类型擦除/通配符/桥接方法），当然是目录**。
--   2. 「max_connections」这种参数在二分里没地方放——它既不是目录也不是标签，
--      它是正文的字。
--
-- 用户给的分界：**看这个名字本身有没有系统性的知识体系**。
--
--   目录 = 能围绕它列出一串关联知识点      泛型、MySQL、序列化
--   标签 = 沾得上、但没有成套体系的         SQL排序、SQL分页、数据库连接
--   正文 = 只是个具体值 / 参数 / 命令        max_connections、SHOW STATUS
--
-- 「能不能列出一串」是个具体动作，模型比理解"要不要单独学"容易照做。
--
-- ## 上一版那句「只有这一条知识会落进去的目录也不要新建」已删
--
-- 那是我加的，本意是防 7 个空目录（Hashmap / JAVA / 中间件 / 工作 / 操作系统 /
-- 测试 / 集合）吸走所有知识。**结果它把真正该发生的那个也挡住了**：
-- 建一个 `MySQL` 目录眼下只有 2 条落进去，正好撞上这句禁令。
--
-- 而且「都不合适就提议新建」那条分支**根本走不到**——`数据库` 永远"合适"，
-- 它是合法的宽目录，模型从来没进过那个分支，自然不会提议 MySQL。
--
-- 删掉之后的前提是：真正把关的东西一直都在（清单近义检查 + 用户预览确认），
-- 建不建目录由用户点，不由提示词替用户决定。
--
-- ## 长度：160 / 163 / 234，都 < varchar(255)
--
-- ⚠️ **organize 只剩 21 字符余量。** 用户说「可以列很多参考例子」——一条 remark
-- 塞不下那么多。如果实机跑完发现还是判不准，**别往 remark 里硬塞**，
-- 得先把「格式说明」和「判据」拆开（判据做成可独立编辑的字典项，
-- 后端按 contexts 拼进去），不然下一次就得删判据了。
-- ============================================================

