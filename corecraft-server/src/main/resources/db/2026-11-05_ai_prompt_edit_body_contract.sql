-- 提示词 `ai.prompt.edit.body` = 「改出来」时的**写法规范**（保留什么、结构怎么跟、术语要解释…）
-- 2026-11-05
--
-- 背景：用户要「对原文的任意修改（增/删/改）都能通过对话完成并应用」。
--   原来这条提示词是给**独立的「AI 调整正文」抽屉**用的（那个抽屉这轮被并进问答抽屉），
--   它只讲一种情况：把正文改写一遍。
--
--   这轮问答抽屉里绝大多数问题是**提问** ⇒ 一轮问答要能出两种东西：
--   ① 用户要的是「一段答案」（提问/解释/比较/举例/总结…）⇒ 正常作答，**不加标记**；
--   ② 用户要的是「一份改好的正文」（新增/替换/删除/扩写/精简/纠错…）⇒ 输出**改写后的完整正文**，
--      前后用 【正文开始】/【正文结束】 包起来 —— 应用侧就靠这两个标记认它是
--      「一份可应用的新正文」，于是**整篇替换**，而不是追加一段。
--
-- **应用侧不解析意图**：改什么、怎么改是模型自己定的（提示词说了算），
--   应用侧只有一条判据 —— 有没有那两行标记。
--
-- ⚠️ **这份配置只管 ② 的"写法"，不管"什么时候该改"**（2026-11-05 晚实测定的）：
--   - 「什么时候该改」（判据：讲明白 / 改出来）+ 输出格式（那两行标记）
--     ⇒ 在**代码里**（前端 `aiEdit.js` 的 `ANSWER_GATE`）——
--     它必须跟用户的话**一起落在最后一条消息**，模型才认得出"这次要什么"。
--     2026-11-05 实测：判据排在材料（钉在第一条）里时，模型最后看到的是
--     **上一轮**的旧问题 ⇒ 它去答了旧问题（实测「改写 2.2」被当成了「解释上一段」）。
--   - 「怎么写」⇒ 就在这份配置里（配置页可改：系统 AI 配置 → AI 提示词 → 正文调整 → 改写规范）。
--   ⇒ 判据只此一份（代码里），别往这份配置里再抄一遍。
--
-- **前端读它，不是后端读** —— 后端那条路（questionKey 命中配置）会把用户自己敲的
--   问题整段替换掉（`instruction.isEmpty() ? req.getQuestion() : instruction`），
--   而这次的要求正是用户自己敲的、每次都不一样 ⇒ 只能走 question（前端自己读配置，
--   跟考试那组 `exam.js` 一个路子）。
--
-- **这是配置不是表结构**：`sys_config.config_value` 一改即时生效，不用发版。
-- 改的是**系统级**提示词（user_id = 0）⇒ 所有人生效。
--
-- 跑前建议（内容级还原）：
--   mysqldump -uroot -p<pwd> corecraft sys_config \
--     --where="user_id=0 AND config_key='ai.prompt.edit.body'" \
--     > <工作区外>/corecraft_pre_edit_body_contract_20261105.sql
--
-- 执行时机：随时（只动 corecraft 库）。


-- ========== ① 跑前自检（这条要命中 1）============
SELECT config_key, CHAR_LENGTH(config_value) AS 长度,
       (config_value LIKE '%改写规则%') AS 是写法规范
  FROM corecraft.sys_config
 WHERE user_id = 0
   AND config_key = 'ai.prompt.edit.body';


-- ========== ② 改 ==========
-- 整段换掉：这份配置的角色变了（"只输出改写后的正文" → "改出来时的写法规范"），
-- 零散地 REPLACE 几处说不清 ⇒ 整条重写。
UPDATE corecraft.sys_config
   SET config_value = '下面是「改出来」时用的写法规范（用户要答案就正常回答，不用这份）。

改写规则：
- **没要求改的部分原样保留**。用户只让新增一节，就别顺手把别的段落也重写。
- **结构跟着原文走**：原文的标题层级、编号、段落划分照抄；新增的小标题接在原文的编号后面继续排。
- **改动直接写进正文**，不要写「（此处新增）」这种占位，也不要单独列一份改动清单。
- **删掉的部分就是不出现**：不留空行、不留「（已删除）」这类痕迹。
- **原文里已经写了的结论以原文为准**，不要拿你记忆里的版本替换它。
- **用户要求新增或扩写的部分，按你自己的知识写**（材料只给了原文，新增的内容材料里当然没有）。
- **标题（# / ##）原样保留**，除非用户明确要求改标题。
- 正文里的 markdown 照常用（标题、列表、表格、代码块），但**不要把整篇正文包进代码块**。
- 写不出来的地方宁可不写，也不要编造事实。
- **术语要解释**：正文里加粗的专业术语，第一次出现时紧跟一句话说清它指什么。
- **补充说明另起一段**：例子、补充、例外另起一段（中间空一行），不要写成上一行的缩进续行。
- **宁可短，不要凑**：不要用套话、排比把常识摊开成段落来充数。',
       update_time = NOW()
 WHERE user_id = 0
   AND config_key = 'ai.prompt.edit.body';


-- ========== ③ 跑后校验（这条要命中 1 / 1）============
SELECT config_key, CHAR_LENGTH(config_value) AS 长度,
       (config_value LIKE '%改写规则%') AS 是写法规范,
       (config_value LIKE '%【正文开始】%') AS 没有输出格式
  FROM corecraft.sys_config
 WHERE user_id = 0
   AND config_key = 'ai.prompt.edit.body';


