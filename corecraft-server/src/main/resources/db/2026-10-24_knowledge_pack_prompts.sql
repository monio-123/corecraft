-- 知识包生成：骨架提示词改写（目录 + 知识点标题）+ 新增「知识点正文」提示词
-- 2026-10-24
--
-- 背景：目录树那个功能做到一半发现**产物不对**——模型顺手列了一堆知识点
-- （"线程生命周期""报文结构与首部"），界面却只建目录，那些条目既没建目录、
-- 也没变成知识，等于凭空消失。
--
-- 用户 2026-10-24 定的新形态：**先出目录骨架（每个目录带知识点标题），
-- 再逐个目录生成知识点正文**。所以：
--
--   ① `ai.prompt.knowledge.outline` 改写：叶子**从"被扔掉的条目"变成"知识点清单"**，
--      并写明"每个目录 3 到 6 个知识点"。
--   ② 新增 `ai.prompt.knowledge.point`：对着标题写正文（带已写清单防重复）。
--
-- ⚠️ **两件事在提示词层面就要分清**：
--    - 骨架阶段**只给知识点标题**（不给正文）—— 一次调用出几十篇正文是不可能的；
--      而且标题先定下来，写正文时对着写，才不会跑题、不会重复。
--    - 正文阶段**只写正文**（标题照抄清单里的）。
--
-- ⚠️ **不再"复用已有目录"**（2026-10-23 那条规则撤了）：用户明确"每次生成的
--    目录和知识点都直接放在第一层，去归属目录这种概念 AI 不好维护"。
--    清单仍然发给模型，但**只用来避开重复造同义目录**，不再要求挂到它们下面。
--
-- 执行时机：随时（配置即时生效，不用发版）。


-- ========== ① 骨架规范（改写） ==========
UPDATE corecraft.sys_config
SET config_value = '把一个主题拆成一套目录树，每个目录下列上这个领域该掌握的知识点。**只输出目录树，不要任何解释、不要开场白。**

材料里给了**主题**，可能还有**现有目录清单**。
- 清单**只用来避开重复造同义目录**（清单里已有「集合」，就别再起一个「集合」）
- 输出的树**自成一体**，全部是新的，**不要挂到清单里的任何目录下**

输出的格式（**必须一模一样**，导入端只认这一种）：
操作系统
├── 进程与线程
│   ├── 进程与线程的区别
│   ├── 进程的状态转换
│   └── 线程的调度策略
└── 内存管理
    ├── 分页与分段的区别
    └── 虚拟内存的工作原理

规则：
- **一层 4 个字符**：`├── ` / `└── `，中间的层用 `│   ` 占位，同级的最后一行用 4 个空格占位
- **目录最多 3 层**：第一个是主题目录，下面是子目录
- **每个目录下 3 到 6 个知识点**（叶子就是知识点标题，一行一个）
- **叶子是知识点标题，不是目录**，它下面不再拆
- **知识点标题是一个能独立记住的结论**，不是章节名（"进程与线程的区别"可以；"进程管理"这种留给目录）
- **目录名不超过 50 个字**
- **一个主题给 12 到 20 个目录**
- 目录名用中文，简短，别写一整句话'
WHERE user_id = 0 AND config_key = 'ai.prompt.knowledge.outline';


-- ========== ② 知识点正文规范（新增） ==========
INSERT INTO corecraft.sys_config (user_id, config_key, config_value, remark)
VALUES (
  0,
  'ai.prompt.knowledge.point',
  '给一个目录写它下面的知识点正文。

材料里给了四样东西：**主题**、**目录路径**、**这个目录要写的知识点标题清单**、**这个主题下已经写过的知识点标题清单**。

每个知识点写成一条独立的知识：
- **标题就用清单里那个**，不要改写、不要合并、不要拆
- **正文是 markdown，300 到 600 字**
- 正文结构：小标题分点（2 到 4 个，**小标题一律用 `###` 开头，不要用 `##`**）+ 要点列表 + 必要的代码 / 命令 / 对比表
- **写给刚入门这个主题的人**：先说清它是什么，再说为什么重要，最后说怎么用、怎么落地
- **要有具体的结论**：能对比就对比、能举例就举例、能量化就量化
- 不要写"学习路线""本章小结""欢迎交流"这类废话
- 不要和清单里其他知识点写重复的内容；**已经写过的不要再写一遍**

格式：每个知识点一段，段与段之间空一行：
## <知识点标题>
<正文>',
  '按目录批量生成知识点正文时整份发给模型。标题照抄骨架给的清单；带已写清单防重复'
);


-- ========== 配置树：新增「知识点正文」叶子 ==========
INSERT INTO corecraft.sys_config_node (parent_id, name, code, config_key, value_type, sort, remark)
SELECT id, '知识点正文', 'point', 'ai.prompt.knowledge.point', 'text', 2,
       '按目录批量生成知识点正文时整份发给模型。标题照抄骨架给的清单；带已写清单防重复'
FROM corecraft.sys_config_node WHERE config_key = 'ai.prompt.knowledge';


