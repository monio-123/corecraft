-- 提示词：骨架的层数上限改成「材料给的 N」，默认 5 层、可选不限
-- 2026-10-27
--
-- 背景：这一轮把**代码里的层数闸全删了**（前端 `MAX_DEPTH`、后端 `MAX_IMPORT_DEPTH`）。
--   为什么删：那道闸只在**导入这一条路**上拦（手工建目录、拖拽移动都不查），
--   而库里早就有了第 5 层的数据（`语言/java/基础/集合/List`）⇒ 它从来没守住过什么，
--   只是一道"贴进来的树太深就报错"的闸 —— 拦错了对象。
--   `kp_category` 是邻接表，层数只是数据；侧边栏缩进撑不住是**显示问题**，
--   该在渲染上解，不该在数据入口拦。
--
--   ⇒ 层数改由**生成骨架时给模型的材料**决定：材料里有一句「层数上限：N 层」，
--   提示词照着办（保底 3 层、最多 N 层；材料写"不限"就不限）。
--
-- **形状规则泛化**：原来提示词把「篇 → 章 → 节」写死三层，还配套说死了
--   ① 每一层放什么 ② 命名序号（模块「2.」/ 章节「2.1」）
--   ③ 总览知识点给哪几层（主题、模块给，章节不给）④ 结构例子
--   —— 这四处**每一处都跟"层数"绑死**，不改就自相矛盾（说了能到 5 层，
--   却还在教模型"第 3 层是章节、下面没有子目录"）。
--
-- **下限仍然是 3 层**：没有下限的话，模型可能只出 2 层（主题 → 模块 → 知识点），
--   章节层和总览的写法都跟着变样 —— 而 3 层是实测过的形状
--   （见 FEATURES.md §2.6「骨架的层数规则去下限」那一条的实测结论）。
--
-- **这是配置不是表结构**：`sys_config.config_value` 一改即时生效，不用发版。
-- 改的是**系统级**提示词（user_id = 0）⇒ 所有人生效。
--
-- **天然幂等**：全部用 REPLACE 定点替换，old 串不存在时 0 行影响 ⇒ 重复跑安全。
--
-- 跑前建议（内容级还原）：
--   mysqldump -uroot -p<pwd> corecraft sys_config \
--     --where="user_id=0 AND config_key='ai.prompt.knowledge.outline'" \
--     > <工作区外>/corecraft_pre_max_depth_20261027.sql
--
-- 执行时机：随时（只动 corecraft 库）。六条互不重叠，顺序任意。


