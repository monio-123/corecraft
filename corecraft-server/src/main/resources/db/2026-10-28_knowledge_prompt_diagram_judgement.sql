      '- **流程图 / 时序图 / 状态图用 mermaid 画**：写成 `mermaid` 代码块（语法照 mermaid 官方：`graph TD` / `sequenceDiagram` / `stateDiagram-v2`）；画不出来的结构就老实用步骤清单或表格表达，别硬画',
      '- **该画图就画图**：判断只有一条 —— **这个知识点用图讲，是不是比用文字讲更清楚**？具体看三条：读者是不是得靠「谁跟谁连着、谁包含谁（结构 / 分层）」「按什么顺序走」「有哪几个状态」才看得懂；有哪一条是这个知识点的核心，就配一张图，写成 `mermaid` 代码块；三条都不是，就别画
