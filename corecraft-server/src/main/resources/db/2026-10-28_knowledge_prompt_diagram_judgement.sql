-- ============================================================
-- 2026-10-28 知识点正文提示词：图从「三选一的祈使句」改成「模型自己判断该不该画」
--
-- ## 为什么要改（这是「图太少」的根因，不是渲染层的问题）
--
-- 现状（改之前）：
--   「**流程图 / 时序图 / 状态图用 mermaid 画**：写成 `mermaid` 代码块
--     （语法照 mermaid 官方：`graph TD` / `sequenceDiagram` / `stateDiagram-v2`）；
--     画不出来的结构就老实用步骤清单或表格表达，别硬画」
--
-- 实测（2026-10-28 查库）：
--   · 全库 795 条知识点：表格 551（69%）、代码块 399（50%）、**mermaid 20（2.5%）**
--   · Java基础 213 条：**只有 5 条带图（2.3%）**，13 个「总览知识点」**一张都没有**
--   · 明显该有图却没有的：extends 与继承层次、异常体系、容器框架结构、
--     new 运算符与对象创建过程、异常传播 ……
--   · 这 213 条是 2026-10-27 生成的 —— 那时提示词**已经**允许画图了
--     ⇒ 「图少」是**当前提示词的稳定行为**，不是老内容没跟上。
--
-- 为什么一句「用 mermaid 画」不够（两个原因）：
--   ① **授权面窄 + 没有触发条件**：只点了三种图型、也没说「哪类知识点该画」
--      ⇒ 模型把「画图」当成「想起来才做」的可选表达形式。
--   ② **给了退路**：那句「画不出来就用步骤清单或表格表达」被当成了「不必画」的许可；
--      而表格本来就写得最勤（69%）⇒ **表格成了图的天然替代品**。
--
-- 对照数据：**禁令型规则模型会遵守**（「不要写图片」795 条里只违反 2 条 = 0.25%），
-- **鼓励型/可选型规则模型基本不遵守** ⇒ 任何「请你也画一张」的软祈使句，
-- 永远打不过「表格更省事」。所以改法不是加一句请求，是**把判断标准写清楚**。
--
-- ## 改成什么样（三条，都是「模型自己判断」，没有配额、没有内容分类）
--
--   ① **判断标准**：图是不是比文字更清楚？具体看三条（谁跟谁连着 / 按什么顺序走 /
--      有哪几个状态），有一条是这个知识点的核心就画；三条都不是就别画。
--   ② **图型自己选**：给的是 **mermaid 的语法清单**（工具能画什么），
--      **不是**「内容类型 → 图型」的映射表（那种映射不该有：内容可能根本不是代码相关，
--      而模型比我们更清楚「这条讲的是关系还是顺序」）。
--   ③ **四条护栏**：最多一张图 / 图里的名词和关系正文都讲过 /
--      不重复表格已对比清的 / 画不出来就用清单或表格别硬画。
--
-- ⚠️ **明确不要配额**：曾考虑过「每个章至少一张图」这种结构性下限，
--    **已否掉** —— 强制就会违反「宁缺毋滥」，变成硬凑一张没用的图。
--    判据交给模型，要画就画，不该画就不画。
--
-- ⚠️ 围栏语言必须仍是 `mermaid`：渲染层就是按这个语言认代码块的
-- （前端 `components/kbMermaid.js`）。
--
-- ⚠️ **执行过两步**（同一天）：先落 v1（判据制），当天又发现**判据漏了「结构 / 分层」**
-- —— 架构、分层、包含关系不是「谁跟谁连着」，是「谁包含谁」
-- ⇒ 补成 v2（下面文件里的就是 v2）。**本文件的正向 / 回滚是净效果**（v0 ⇄ v2）。
--
-- 执行时机：一次性迁移（已执行）。
-- ============================================================

-- ------------------------------------------------------------
-- 0. 跑前自检
--    ① `ai.prompt.knowledge.point` 存在（user_id=0）。
--    ② 那句旧文案还在（v0）—— **本脚本的正向只匹配 v0**：
--       v1（判据制，中间那版）没有落成脚本、仓库里不存在 ⇒
--       重放顺序必须是「先回滚到 v0 → 再跑本脚本」，别改成 v1。
--    ③ 新的那句已经不在（已改过的话这段会跳过，重跑安全）。
-- ------------------------------------------------------------
SELECT 'point配置行(应为 1)' AS 检查项, COUNT(*) AS 数量
  FROM `corecraft`.`sys_config`
 WHERE `user_id` = 0 AND `config_key` = 'ai.prompt.knowledge.point'
UNION ALL
SELECT '旧文案v0还在(应为 1)', COUNT(*)
  FROM `corecraft`.`sys_config`
 WHERE `user_id` = 0
   AND `config_key` = 'ai.prompt.knowledge.point'
   AND `config_value` LIKE '%- **流程图 / 时序图 / 状态图用 mermaid 画**%'
UNION ALL
SELECT '新文案已在(应为 0)', COUNT(*)
  FROM `corecraft`.`sys_config`
 WHERE `user_id` = 0
   AND `config_key` = 'ai.prompt.knowledge.point'
   AND `config_value` LIKE '%- **该画图就画图**%';

-- ------------------------------------------------------------
