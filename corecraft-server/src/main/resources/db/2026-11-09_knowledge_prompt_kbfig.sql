-- ============================================================================
-- 知识点正文提示词：加入结构化图（```kbfig）
--
-- 日期：2026-11-09
-- 目标配置：sys_config / ai.prompt.knowledge.point（user_id = 0）
--
-- ## 为什么改
--
-- 用户反馈两件事：①「生成的内容对于某些内容生成的图的效果很差，优美质感基本为 0，
-- 表达效果也不好」；②「要表达一个知识内容除了图/代码块/表格之外应该还有一些其他的场景」。
--
-- 换肤（同日 #811）只解决了配色，**布局是 mermaid 的天花板**：graph TD 走 dagre
-- 自动布局，节点只能是方块 + 箭头 + 文字标签，画不了「一个整体包含哪几块」
-- 「这几步同属一个阶段」「每一步吃什么吐什么」—— 这些只能摊成一族长标签。
--
-- 实测（2026-11-09 回测，deepseek-flash，库内 14 条真实知识点）：
--   · 11 条输出 kbfig JSON，**全部合法且字段合规**（100%）
--   · 2 条选了 mermaid（批处理 / 分时系统 —— 判断正确，那是流程）
--   · 1 条被 max_tokens 截断（JSON 没写完）⇒ 提示词里必须限制长度，渲染层也要兜底
--   ⇒ 这条路可行，改提示词启用。
--
-- ## 改了哪三处
--
-- ① 「该画图就画图」：判据从三条扩到四条（补「包含/分层」「每组输入产出」「一一对应」）
-- ② 「图型你自己选」→ 换成「两种画法 + 结构化图三种形状 + 硬规矩」
--    删掉「讲包含/分层优先 mindmap」那句 —— 它现在和 layers 抢同一类内容
-- ③ 「图的硬规矩」：明确一张图的额度由两种图共用
--
-- ⚠️ 三段 REPLACE **一次改完**、各带 LIKE 守卫：分三次改同一行会出现半新半旧的中间版本。
-- ⚠️ 生效时机：sys_config 每次生成时读库 ⇒ 改完立即生效，但**生成中的任务不吃新 prompt**。
--
-- 执行方式：三段 UPDATE 分开跑（MCP 逐条执行），跑后校验见文件末尾。
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 【跑前校验】确认三段原文都在（三个值都应为 1）
-- ---------------------------------------------------------------------------
SELECT
  SUM(config_value LIKE '%- **该画图就画图**：判断只有一条%')                AS 段1命中,
  SUM(config_value LIKE '%- **图型你自己选**（mermaid 支持的%')              AS 段2命中,
  SUM(config_value LIKE '%- **图的硬规矩**：①一个知识点最多一张图%')        AS 段3命中,
  CHAR_LENGTH(MAX(config_value))                                            AS 改前总长
FROM `corecraft`.`sys_config`
WHERE `user_id` = 0 AND `config_key` = 'ai.prompt.knowledge.point';


-- ---------------------------------------------------------------------------
-- 【第 1 段】判据：三条 → 四条，并加一条"表格能说清就别配图"
-- ---------------------------------------------------------------------------
UPDATE `corecraft`.`sys_config`
SET `config_value` = REPLACE(
  `config_value`,
  -- 旧
  '- **该画图就画图**：判断只有一条 —— **这个知识点用图讲，是不是比用文字讲更清楚**？具体看三条：读者是不是得靠「谁跟谁连着、谁包含谁（结构 / 分层）」「按什么顺序走」「有哪几个状态」才看得懂；有哪一条是这个知识点的核心，就配一张图，写成 `mermaid` 代码块；三条都不是，就别画',
  -- 新
  '- **该画图就画图**：判断只有一条 —— **这个知识点用图讲，是不是比用文字讲更清楚**？看这几条：读者是不是得靠「谁跟谁连着」「谁包含谁、分成哪几层」「按什么顺序走、每一步吃什么吐什么」「两组东西怎么一一对应」「有哪几个状态」才看得懂；有一条是这个知识点的核心，就配一张图；一条都没有，就别画。**表格已经能对比清楚的，不要再配图**'
)
WHERE `user_id` = 0
  AND `config_key` = 'ai.prompt.knowledge.point'
  AND `config_value` LIKE '%- **该画图就画图**：判断只有一条 —— **这个知识点用图讲，是不是比用文字讲更清楚**？具体看三条%';


-- ---------------------------------------------------------------------------
-- 【第 2 段】图型选择：换成「两种画法」+ 结构化图三种形状（带三个 JSON 例子）
--
-- ⚠️ 例子是这个 prompt 里最重要的部分：模型模仿 JSON 结构的能力远强于理解文字描述。
-- ⚠️ 删掉「讲包含/分层优先 mindmap」—— 现在这类内容归 layers，不归 mermaid。
-- ---------------------------------------------------------------------------
UPDATE `corecraft`.`sys_config`
SET `config_value` = REPLACE(
  `config_value`,
  -- 旧
  '- **图型你自己选**（mermaid 支持的：关系图 `graph TD` / `graph LR`、时序图 `sequenceDiagram`、状态图 `stateDiagram-v2`、类图 `classDiagram`、ER 图 `erDiagram`、甘特图 `gantt`、思维导图 `mindmap`、时间线 `timeline`）—— 按内容挑最贴切的那种，别硬套。**几条判断线索**：讲「包含 / 分层 / 组成」的优先 `mindmap`；讲「版本演进 / 历史变迁」的用 `timeline`；讲「多个角色按先后交互」的用 `sequenceDiagram`；讲「有哪几个状态、怎么流转」的用 `stateDiagram-v2`。**`graph TD` 只留给「步骤 / 判断分支」** —— 它笔画最少、最容易画，别把它当默认',
  -- 新
  '- **图的两种画法，先定用哪种**（这是画图的第一步，别跳过）：\n  - **结构化图**（写成 ```kbfig 代码块，内容是 JSON）：「一个整体包含哪几块、块里还有什么」「按顺序的步骤（尤其每一步有输入或产出）」「两组东西一一对应」。这类内容 mermaid 画出来是一族长标签，读者看不出层次。\n  - **mermaid**（写成 ```mermaid 代码块）：「谁跟谁连着（调用 / 依赖）」「有哪几个状态、怎么流转」「多个角色按先后交互」「版本演进 / 历史变迁」「**带判断分支的流程**」。需要自动布局的都用它。\n  - **分工边界**：「按顺序走」默认用结构化图的 `stages`；**只有出现「如果…就…否则…」的分支**才用 mermaid 的 `graph` —— 分支要画菱形，结构化图不画这个。\n- **结构化图只有三种形状**（`type` 只能取 `layers` 或 `stages`，字段名照抄例子）：\n  - `layers` —— 分层 / 包含：\n```kbfig\n{"type":"layers","title":"JVM 运行时数据区","groups":[{"name":"线程私有","note":"每线程一份","items":[{"t":"程序计数器","d":"当前字节码行号"},{"t":"虚拟机栈","d":"栈帧 / 局部变量表"}]},{"name":"线程共享","note":"全进程一份","items":[{"t":"堆","d":"GC 主战场","tags":["Eden","S0","S1","Old"]}]}]}\n```\n  - `stages` —— 顺序 / 阶段；**子步骤用 `steps` 嵌套**，表示「这几个同属一个阶段」：\n```kbfig\n{"type":"stages","title":"类的生命周期","steps":[{"t":"加载","d":"读字节码，生成 Class 结构"},{"t":"连接","d":"Linking","steps":[{"t":"验证","d":"字节码合法"},{"t":"准备","d":"静态变量赋零值"},{"t":"解析","d":"符号引用转直接引用"}]},{"t":"初始化","d":"执行 <clinit>"},{"t":"卸载","d":"类加载器可回收时"}]}\n```\n  - `stages` + 侧翼 —— 每一步有**明确的输入或产出**时，加 `from`（从哪来）/ `out`（产出什么）/ `note`（旁注）；`hl: true` 标「整条链路里只出现一次」的那个节点，**最多一个**：\n```kbfig\n{"type":"stages","steps":[{"t":"规则路由","d":"纯代码，不调模型","from":"企微消息","out":"预设场景 4 选 1","note":"命中不到就回 help"},{"t":"取数","d":"腾讯文档只读","from":"定时任务","out":"结构化数据"},{"t":"LLM","d":"只出现一次","hl":true}]}\n```\n- **结构化图的硬规矩**：标题 ≤ 14 字、说明 ≤ 26 字；`stages` 步骤 ≤ 6 个（含子步骤 ≤ 8）；`layers` ≤ 4 组、每组 items ≤ 5 个；**不许写颜色、宽度、位置、坐标**（样式全由渲染组件决定）；JSON 里**不许出现裸的双引号**（要引号就写「」）；必须是**合法 JSON**（键和字符串都用双引号、最后没有多余逗号）。**超了会被截断，图就残了**'
)
WHERE `user_id` = 0
  AND `config_key` = 'ai.prompt.knowledge.point'
  AND `config_value` LIKE '%- **图型你自己选**（mermaid 支持的%';


-- ---------------------------------------------------------------------------
-- 【第 3 段】额度：一张图的额度由两种图共用（否则模型可能各画一张）
-- ---------------------------------------------------------------------------
UPDATE `corecraft`.`sys_config`
SET `config_value` = REPLACE(
  `config_value`,
  '- **图的硬规矩**：①一个知识点最多一张图；',
  '- **图的硬规矩**：①一个知识点最多一张图（结构化图和 mermaid 共用这一个额度，别各画一张）；'
)
WHERE `user_id` = 0
  AND `config_key` = 'ai.prompt.knowledge.point'
  AND `config_value` LIKE '%- **图的硬规矩**：①一个知识点最多一张图；%';


-- ---------------------------------------------------------------------------
-- 【跑后校验】五项都应命中，总长从 3740 涨到 4800 上下
-- ---------------------------------------------------------------------------
SELECT
  SUM(config_value LIKE '%图的两种画法，先定用哪种%')        AS 段1两种画法,
  SUM(config_value LIKE '%图型你自己选%')                    AS 旧图型句残留,
  SUM(config_value LIKE '%优先 `mindmap`%')                  AS 旧mindmap引导残留,
  SUM(config_value LIKE '%```kbfig%')                        AS 结构化图说明,
  SUM(config_value LIKE '%共用这一个额度%')                  AS 额度共用,
  SUM(config_value LIKE '%"type":"layers"%')                 AS 例子layers,
  SUM(config_value LIKE '%"type":"stages"%')                 AS 例子stages,
  CHAR_LENGTH(MAX(config_value))                             AS 改后总长
FROM `corecraft`.`sys_config`
WHERE `user_id` = 0 AND `config_key` = 'ai.prompt.knowledge.point';


