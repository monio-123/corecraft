-- 知识包生成规范 v3：总览知识点的树形位置写死 + 正文必须按清单顺序输出
-- 2026-10-24（晚，接 v2）
--
-- v2 已经把"三层目录 + 术语命名 + 有下级的那层挂总览知识点"写进提示词了，
-- 但有两处**模型会猜错、猜错了前端察觉不到**：
--
--   ① **总览知识点在树里的位置**没写死。v2 只说"放在它的知识点第一个"，
--      模型可能理解成"排在所有知识点之前"（也就是放在章节层，而不是这个目录下面）。
--      位置错了 ⇒ 总览知识点会挂到**下一层目录**去，统筹的作用就没了。
--      v3 用一句话把它钉死："写成这个目录的**第一个子条目**（和下级目录平级）"，
--      并补一个**结构例子** —— 例子比描述可靠。
--
--   ② **正文顺序**没写死。v2 说"标题照抄清单里的"，没说"顺序不许调换"。
--      模型把两条换了顺序 ⇒ 前端按位置对齐就会把 A 的正文挂到 B 的标题上，
--      **而且不报错**（卡片有正文，只是讲的是别的东西）。
--      这轮前端已经把解析器改成**按标题对齐**（`utils/knowledgePoints.js`），
--      提示词这边补上"按清单顺序输出"，两头都堵上。
--
-- 这个脚本改两条提示词：
--   ① `ai.prompt.knowledge.outline`（骨架）：总览知识点的位置 + 结构例子 + 总数口径
--   ② `ai.prompt.knowledge.point`（正文）：按清单顺序输出
--
-- 执行时机：随时（配置即时生效，不用发版）。


-- ========== ① 骨架规范 ==========
UPDATE corecraft.sys_config
SET config_value = '把一个主题拆成一套能照着学的目录树，每个章节下列上这个领域该掌握的知识点。**只输出目录树，不要任何解释、不要开场白。**

材料里给了**主题**，可能还有**现有目录清单**。
- 清单**只用来避开重复造同义目录**（清单里已有「集合」，就别再起一个「集合」）
- 输出的树**自成一体**，全部是新的，**不要挂到清单里的任何目录下**

层级（**必须三层目录，不许跳**）：
- 第 1 层：**主题目录**（如「操作系统」）
- 第 2 层：**模块目录**（如「2. 进程管理」）
- 第 3 层：**章节目录**（如「2.1 进程基础」）
- 叶子：**知识点标题**，挂在它所在目录的下面

规则：
- **一层 4 个字符**：`├── ` / `└── `，中间的层用 `│   ` 占位，同级的最后一行用 4 个空格占位
- **模块和章节带序号**（"2."、"2.1"），体现学习顺序；主题目录不带序号
- **模块 5 到 8 个**，每个模块下 **3 到 5 个章节**，每个章节下 **3 到 5 个知识点**
- **全树知识点总数不超过 120 条**（超了就减章节数，别减每章的知识点数）
- **凡是下面还有子目录的那一层（主题、模块），自己也要有一个知识点**，写成这个目录的**第一个子条目**（和下级目录平级，排在最前），是**总览**：这个主题/模块讲什么、包含哪几个下级目录、各自的重点
- **知识点名是标准术语或名词短语**，不是陈述句
  - 对：「进程上下文切换」「PCB（进程控制块）」「进程终止」「内核态与用户态」「银行家算法」
  - 错：「进程上下文切换需要保存寄存器」「进程终止会释放所占资源」「进程创建后进入就绪队列」
  - 理由：名字要能当**检索词**、能当**卡片标题**；结论、原理、对比写进正文
- **每个知识点是一个能独立记住的结论**，粒度到"一个概念 / 一种算法 / 一组辨析"
- **目录名不超过 50 个字**

结构例子（**照这个层次来，内容换成主题自己的**）：
计算机网络
├── 计算机网络总览
├── 1. 物理层
│   ├── 物理层导览
│   ├── 1.1 传输介质
│   │   ├── 双绞线
│   │   └── 光纤
│   └── 1.2 信道容量
│       ├── 奈奎斯特准则
│       └── 香农定理'
WHERE user_id = 0 AND config_key = 'ai.prompt.knowledge.outline';


-- ========== ② 知识点正文规范 ==========
UPDATE corecraft.sys_config
SET config_value = '给一个目录写它下面的知识点正文。

材料里给了：**主题**、**目录路径**、**这个目录现有的子目录**、**这个主题下已经写过的知识点标题清单**。可能还给了**这次要写的知识点标题清单**，以及**这个目录下面的章节和它们各自的知识点**（总览知识点要用；章节后面带地址的，把章节名写成链接）。

**给了标题清单**时：
- 标题照抄清单里的，不要改写、不要合并、不要拆。
- **按清单给的顺序输出，一条都不能少，顺序不许自己调换。**

**没给标题清单**时：先自己定这个目录该有的 3 到 5 个知识点标题，再按同样的格式写正文。

每个知识点写成一条独立的知识：
- **标题就是术语名词**（清单里是什么就用什么），不要写成陈述句
- **正文是 markdown，400 到 800 字**
- 正文按四段写：
  1. **是什么**：一句话说清定义、全称、所属领域
  2. **怎么运作**：机制、流程、要点清单；必要时带一句真实工程里怎么用（后端/云原生视角）
  3. **易混辨析**：和哪个概念容易混、区别在哪（一两条说清，没有相近概念就不写这段）
  4. **面试怎么问**：可能的问法 + 一句话答案
- **小标题一律用 `###` 开头，不要用 `##`**（`##` 是知识点的分隔标记）
- **要有具体的结论**：能对比就对比、能举例就举例、能量化就量化
- 不要写"学习路线""本章小结""欢迎交流"这类废话
- **不要和这个目录现有的子目录重复**（子目录已经覆盖的领域就别在这里再写）
- 不要和清单里其他知识点写重复的内容；**已经写过的不要再写一遍**
- **总览知识点**（材料里给了下级章节和它们的知识点时）：正文写成这个主题/模块的**索引** —— 它讲什么、分成哪几个章节、每个章节讲什么、重点和难点在哪，并把下级章节和知识点的名字列出来
- **总览知识点里提到下级章节时，章节名写成 markdown 链接**：材料里给了地址就照抄（`[章节名](地址)`）；没给地址就写普通文字，**不要自己编地址**

格式：每个知识点一段，段与段之间空一行：
## <知识点标题>
<正文>'
WHERE user_id = 0 AND config_key = 'ai.prompt.knowledge.point';


