-- ============================================================
-- 目录 = 主归属，标签 = 其余涉及的（2026-10-07，第六轮判据）
--
-- ## 起因：单选目录 + 「目录级概念不许当标签」= 有些概念无处安放
--
-- `kp_topic.category_id` 是**单列**，一条知识只能待在一个目录里。但一条知识常常
-- 同时属于好几个有体系的东西——「MyBatis 一对多映射分页」既是 MyBatis 的也涉及 MySQL。
-- 选了 `MyBatis` 之后，`MySQL` 就无处可去。
--
-- 而前几轮我在提示词里写死了「MySQL、JDBC 这类技术栈名是目录的活，别放这里」——
-- **加上单选目录这个硬约束，就等于宣布「MySQL 这种概念在有些知识里无法表达」**。
-- 那是死规则，而且**是我自己加的，用户从没要求过**。
--
-- ## 新的判据：不是「这个概念够不够格」，是「它是不是这次的主归属」
--
--   1. 它是概念吗？  不是（具体值/命令/参数）→ 正文
--   2. 它是主归属吗？是 → 目录
--   3. 否则          → 标签
--
-- **标签不是"档次低的概念"，是"这次不是主归属的概念"。** 同一个 `MySQL`：
--   - 「MySQL 连接数怎么看」   主归属是它 → 目录
--   - 「MyBatis 一对多映射分页」主归属是 MyBatis → `MySQL` 当标签，**这不是退而求其次**
--
-- 这本来就是 skill §2.2 早就写的那句「目录管『属于哪个』、标签管『涉及什么』」，
-- 是我在推导过程中把"涉及什么"收窄成了"档次低的什么"。
--
-- ## 顺带把"标签分两类"这件事做进界面
--
--   A 类（次归属）：目录树里也有同名条目 —— 概念够格当目录，只是没挤进去 → **蓝底蓝字**
--   B 类（普通）：目录树里没有 —— 就是普通概念（SQL排序、SQL分页、数据库连接）→ 灰底灰字
--
-- **判据不从 AI 来，从目录树推**（`isDomainLevelTag`）。理由：**用户自己建了哪些目录，
-- 就是他认为什么够格当目录**；让模型再判断一遍，那是拿一份写死的名单替它做决定
-- ——#89/#90 踩过：词表污染了实验，分不清是判据起作用还是照抄名单。
--
-- 顺带白送一个提醒：**一堆 A 类标签** = 「这批知识在那一支都有位置，该建目录迁过去了」。
-- 所以不用专门做"标签升格成目录"的功能，颜色本身就是提示。
--
-- ## 明确不做：把目录改成多选
--
-- 那会让目录和标签彻底没区别，`category_id` 单列要变关联表——**推翻 §2.2 的核心决策**。
--
-- 长度：254 / 345 / 437，都 < varchar(1000)。
-- ============================================================

UPDATE `sys_dict_item` SET `remark` = '这条知识该归到哪个目录。

判断标准：这条知识主要在学谁，就归谁。
- 「MyBatis 一对多映射的分页」主要在讲 MyBatis → 目录 MyBatis；顺带涉及的 MySQL 写进标签
- 「MySQL 连接数怎么看」主要在讲 MySQL → 目录 MySQL
- 成套知识体系的概念（泛型、序列化）通常就是主归属

清单里有合适的就选最贴近的那一层，有更具体的别选更宽的。
要新建就用斜杠写出它该挂在哪下面：挂「数据库」下的新目录写「数据库/MySQL」。
只输出路径本身，不要写理由、不要加括号。'
WHERE `dict_type_id` = (
  SELECT id FROM `sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `value` = 'pick_category:categories' AND `is_delete` = 0;

UPDATE `sys_dict_item` SET `remark` = '这条知识涉及哪些概念——主归属之外的那些。

主归属已经在目录里了，标签装的是剩下的。目录只能选一个，所以一条知识同时涉及好几个有体系的东西时，题目主要在讲哪个归哪个目录，其余的——哪怕它本身也是个正经的技术栈（一条讲 MyBatis 的笔记顺带说了 MySQL 的分页，MySQL 就写在这儿）——都放到标签里。

具体数值和命令不是标签（max_connections、SHOW STATUS），那是正文。
粒度要说清是哪种：「排序」太笼统，分不清是数据库里排、Java 对象里排还是 List 里排。

数量 0 到 4 个，宁缺毋滥。凑出来的标签是垃圾，比没有还糟。
下面的清单只是「你已经用过哪些叫法」，用来统一叫法，它不是推荐清单。
每行只写标签名本身，不要写理由、不要加括号。'
WHERE `dict_type_id` = (
  SELECT id FROM `sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `value` = 'pick_tags:tags' AND `is_delete` = 0;

UPDATE `sys_dict_item` SET `remark` = '这次一次给全，按下面三段输出，不要写别的解释：

名字：<12 字以内说清它讲什么，不要「详解」「介绍」「学习笔记」这类空词>

目录：<这条知识主要在学谁，就归谁。题目主要在讲哪个就归哪个目录；又涉及别的东西写进标签。
清单里有合适的就选最贴近的那一层。要新建就用斜杠写出它该挂在哪下面，
比如挂「数据库」下的新目录写「数据库/MySQL」。只输出路径本身，不要写理由、不要加括号。>

标签：
- <这条知识涉及、但主归属之外的那些。目录只能选一个，所以同时涉及好几个有体系的东西时，
其余的哪怕本身也是正经技术栈（一条讲 MyBatis 的笔记顺带说了 MySQL 分页，MySQL 就写这儿）也放这儿。
具体数值和命令不算标签（max_connections、SHOW STATUS），那是正文。
粒度要说清是哪种：「排序」太笼统，分不清是数据库里排、Java 对象里排还是 List 里排。0 到 4 个，宁缺毋滥。
每行只写标签名本身，不要写理由、不要加括号。>'
WHERE `dict_type_id` = (
  SELECT id FROM `sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `value` = 'organize:categories,tags' AND `is_delete` = 0;
