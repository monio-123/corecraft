-- 目录树生成规范：加"能写几层"（层数预算是相对的，挂载点占了几层要算进去）
-- 2026-10-23
--
-- 背景：上一版把"最深 4 层（从根算起）"写进了规范，但**没告诉模型"从根"是哪儿**。
-- 实测（2026-10-23，真后端 + 真模型 + 前端真解析器）：
--   - 挂在根下生成：最深 4 层 ✔ 合规
--   - 挂在「语言/java」（第 2 层）下生成：模型写到了**第 5 层** ✘ 超限
-- 原因是模型按**自己那棵树从 1 数**（"我写了 3 层，没超 4"），
-- 而真实约束是**绝对层数**（挂载点已经占了 2 层，只剩 2 层归它）。
--
-- 修法（两处，缺一不可）：
--   ① 规范里加一条：能写几层**以材料里说的为准**（材料里会给出这个数字）。
--   ② 前端 material 里把预算算好告诉模型："你在第 2 层，最多写 2 层"。
--      **算预算的那份代码在前端**（挂载点的真实层数只有它知道）。
--
-- ⚠️ 事后校验（前端标红 + 后端报错）仍然保留，但降级成兜底：
--    模型不听话时拦得住，而不是把不合规的树直接写进库。
--
-- 执行时机：随时（配置即时生效，不用发版）。


-- ========== 规范文本 ==========
UPDATE corecraft.sys_config
SET config_value = '把一个主题拆成一套目录树。**只输出目录树，不要任何解释、不要开场白。**

材料里给了**主题**，可能还有**现有目录清单**（缩进表示层级）和**挂载点**。
- **优先复用已有目录**：清单里有的就用它，不要另起一个同义的新目录
- 给了**挂载点**时，只写挂载点**下一层**开始的那一支，不要把挂载点自己再写一遍
- **能写几层以材料里说的为准**：挂载点占了几层，剩下几层才归你，写超了建不了
- 清单里完全没有的（新领域）就新起一个顶层目录

输出的格式（**必须一模一样**，导入端只认这一种）：
主题
├── 子目录 A
│   ├── 条目 A1
│   └── 条目 A2
└── 子目录 B

规则：
- **一层 4 个字符**：`├── ` / `└── `，中间的层用 `│   ` 占位，同级的最后一行用 4 个空格占位
- **目录名不超过 50 个字**
- **最深 4 层，从根算起**。材料里说明了还能写几层时，**以那个为准**
- **一次不超过 300 个目录**
- 目录名是**领域或主题**（"传输层"、"容器网络"、"索引优化"），不是流程、场景、状态（"日常"、"上线流程"、"待办"）—— 目录是这条知识**主要在学谁**
- 目录名只写领域/主题本身，**不带序号**（挂在已有体系下，序号会乱）
- 同一层不要出现意思重复的目录；不同父下同名是允许的
- **叶子是知识点**（"传输介质：双绞线、光纤"这种内容），不是目录：照常列出来，但不用再往下拆
- 一个主题给 10 到 30 个目录就够，别把知识点全铺成目录
- 目录名用中文，简短，别写一整句话'
WHERE user_id = 0 AND config_key = 'ai.prompt.knowledge.outline';


