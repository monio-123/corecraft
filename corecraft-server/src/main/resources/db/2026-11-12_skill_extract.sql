- **结构化图的硬规矩**：标题 ≤ 14 字、说明 ≤ 26 字；`stages` 步骤 ≤ 6 个（含子步骤 ≤ 8）；`layers` ≤ 4 组、每组 items ≤ 5 个；`pairs` ≤ 6 行、左边 ≤ 10 字、右边 ≤ 20 字、`left`/`right` ≤ 8 字；**不许写颜色、宽度、位置、坐标**（样式全由渲染组件决定）；JSON 里**不许出现裸的双引号**（要引号就写「」）；必须是**合法 JSON**（键和字符串都用双引号、最后没有多余逗号）。**超了会被截断，图就残了**
