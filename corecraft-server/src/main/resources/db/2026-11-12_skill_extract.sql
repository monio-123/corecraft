```kbfig
{"type":"stages","steps":[{"t":"规则路由","d":"纯代码，不调模型","from":"企微消息","out":"预设场景 4 选 1","note":"命中不到就回 help"},{"t":"取数","d":"腾讯文档只读","from":"定时任务","out":"结构化数据"},{"t":"LLM","d":"只出现一次","hl":true}]}
```
  - `pairs` —— **两组一一对应**：左边一个术语 / 一个码 / 一个策略，右边是**它的解释或后果**（例：原则 ↔ 解决的问题、状态码 ↔ 触发场景）。⚠️ **两个对象逐项比取值用表格、不用这个**（两种实现的延迟各是多少 —— 那是取值，不是对应关系）。`left` / `right` 是两个列名，**两个都要给**（只给一个等于一列表头）；每行 `l` 是左边、`r` 是右边：
```kbfig
