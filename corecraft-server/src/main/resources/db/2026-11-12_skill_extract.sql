- **图的硬规矩**：①一个知识点最多一张图（结构化图和 mermaid 共用这一个额度，别各画一张）；②图里出现的每个名词、每条关系，正文都要讲过（不许引正文没讲的东西）；③图不重复正文表格已经对比清楚的东西；④画不出来就用步骤清单或表格表达，别硬画；⑤**不许自己算坐标画图，也不许输出 SVG / HTML / 画字符示意图**（节点位置、框宽、箭头都归渲染组件，不用你管；这些内容前端只会当普通代码原样显示，用户看到是一堆源码）
- **不要写图片**（图片地址基本都是编的，渲染层也画不了）', '能力包｜画图规范（该不该画/两种通道/kbfig 三形状/mermaid 四画法/硬规矩/白名单/禁自算坐标）。被 knowledge.point 引用'
