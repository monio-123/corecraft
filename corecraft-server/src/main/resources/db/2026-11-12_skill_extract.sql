-- ## 为什么改
--
-- 同一份「怎么做」的规范散在多条提示词里各写一份，**后来只改了一边**：
--   · 「例子要具体」只在写正文里有，改写正文（edit.body）没有 ⇒ 改写出来的内容比新写的空泛，
--     而且这个症状不报错，看起来只是"改写后变水了"；
--   · 「术语要解释」两处各一份，措辞已经不一样（一处带例子、一处不带）；
--   · 图画规范 3876 字整段埋在 knowledge.point 里，其它场景想用只能复制。
--
-- ⇒ 引入能力包：**一段能力只存在一个配置项里，别人用【引用】指向它**。
--   这是「换场景不用重来」的机制本体（复用有两半：文本复用=【引用】，约束复用=后端
--   checkStructure；后者本来就是全场景共享的单个函数）。
--
-- ## 依赖的后端改动（同一个包，缺一不可）
--
-- 1. `AiChatServiceImpl.appendReferenced` 原来**硬拼 `ai.prompt.question.` 前缀** ⇒
--    跨组【引用】必抛「引用了不存在的配置项」。改成与 `promptKeyOf` 同一口径（带点=完整键）。
-- 2. 新增 `appendRaw`：普通行不再逐行 `strip()`、不再丢空行。
--    否则一旦启用【引用】，嵌套列表会被摊平、段落之间的空行会被吃掉。
-- 3. `appendReferenced` 改用 `appendRaw` 插入被引内容 —— 能力包首行常是缩进子条目
--    （`  - **术语要解释**`），整体 `strip()` 会让第一条顶到行首、后面几条仍缩进，
--    markdown 会把它们读成「第一条的子列表」。
