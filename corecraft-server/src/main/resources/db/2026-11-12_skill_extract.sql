```
  - `stages` —— 顺序 / 阶段；**子步骤用 `steps` 嵌套**，表示「这几个同属一个阶段」：
```kbfig
{"type":"stages","title":"类的生命周期","steps":[{"t":"加载","d":"读字节码，生成 Class 结构"},{"t":"连接","d":"Linking","steps":[{"t":"验证","d":"字节码合法"},{"t":"准备","d":"静态变量赋零值"},{"t":"解析","d":"符号引用转直接引用"}]},{"t":"初始化","d":"执行 <clinit>"},{"t":"卸载","d":"类加载器可回收时"}]}
```
