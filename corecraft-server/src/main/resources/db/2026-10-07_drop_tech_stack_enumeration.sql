-- ## 同样是 MySQL 这个词，两种用法完全不同
--
-- 穷举（错的）：「MySQL、JDBC、Redis… 一律是目录级的」
--   → 模型学到的是**查表**。名单外的词它就不知道了。
--
-- 判据示范（对的）：
--   「MySQL 是目录：围绕它能问出一串互不相同的问题——怎么连、索引怎么建、
--     事务隔离级别、怎么主从复制。」
--   「SQL排序 不是目录：它就是那一个问题本身，围绕它问不出别的第二个问题。」
--   「max_connections 连标签都不该有：它是一个具体数值，在正文里写一次就
--     够了，记住它没有任何检索价值。」
--   → 模型学到的是**判据**。
