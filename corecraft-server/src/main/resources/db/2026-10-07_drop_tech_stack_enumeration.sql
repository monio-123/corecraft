UPDATE `sys_dict_item` SET `remark` = '这条知识该归到哪个目录。

判断标准：这个词本身是不是通往一串相关知识的入口。
- MySQL 是目录：围绕它能问出一串互不相同的问题——怎么连、索引怎么建、事务隔离级别、怎么主从复制。
- SQL排序 不是目录：它就是那一个问题本身，围绕它问不出别的第二个问题。
- max_connections 连标签都不该有：它是一个具体数值，在正文里写一次就够了，记住它没有任何检索价值。

怎么挑：清单里选最贴近的那一层。有更具体的就别选更宽的——清单里同时有「MySQL」和「数据库」而这条讲 MySQL，就选 MySQL。
如果清单里只有「数据库」这种宽泛的名字，而这条明显属于某个更具体的方向，就把你认为该叫的名字当新目录名提出来。
提之前先看清单里有没有近义的，有就归过去，别造一个几乎一样的。'
