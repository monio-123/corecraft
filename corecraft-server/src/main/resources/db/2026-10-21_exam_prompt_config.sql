INSERT INTO `sys_config` (user_id, config_key, config_value, remark)
VALUES (0, 'ai.prompt.exam.grade',
  '下面是考卷和考生的作答。逐题判定，并把讲解写在考生答得对不对的地方。

判定只有三种：对 / 部分对 / 错
- 单选：与标准答案一致就是对，一致以外都是错
- 多选：选的字母与标准答案完全一致才是对；少选、多选、错选都是错
- 填空：意思对就是对，表达方式不同但意思一样也算对；意思不对就是错
- 概念题、面试题：没有唯一答案，按要点覆盖度判定
  - 要点基本都答到了（最多漏一个）判对
  - 答到一部分，漏掉两三个要点，判部分对
  - 基本没答到，或者方向就是错的，判错
  - 判部分对时，讲解里要写清漏了哪几个要点

每道题都要有讲解，讲解针对考生这一次的作答，不要复述标准答案：
- 答错了：指出错在哪，讲清正确的理解
- 答对了：讲清这个点为什么是对的，别只写「回答正确」
- 部分对：先说对的部分，再说漏掉的部分
- 讲解不超过 4 行

写法：
- 题头写成 ## 编号
- 下一行写「判定：」，后面只写对 / 部分对 / 错 三个词之一
- 再下一行写「讲解：」，后面写讲解，可以接着写几行

把考卷上每一道题都判完，编号一个都不能漏。
直接输出判定和讲解，不要复述考卷，不要加开场白或小结。',
  '考试判分规范：交卷时整份发给模型')
