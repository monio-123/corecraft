-- 考试模式（demo）：两份输出规范 + 配置树上的位置
--
-- 【背景】
-- 考试模式是**零建表、零存储**的 demo：卷子只活在浏览器内存里，刷新就没了。
-- 它不需要新接口，也不需要新表——出题和判分走的是现成的问答通道
-- （/ai/chat/stream），区别只在于**提示词用的是完整配置键**
-- （ai.prompt.exam.paper / ai.prompt.exam.grade）。
--
-- 后端为此只加了一个判断：questionKey 带点就当完整键
-- （原来只认 ai.prompt.question. 前缀的短名）。
--
-- 【规范就是配置项】
-- 这两段文本是**我们自己定的输出规范**，前端按它解析
-- （corecraft-web/src/views/corecraft-web/examParse.js）。
-- 管理员在「系统管理 → 系统配置 → 系统 AI 配置 → AI 提示词 → 考试」
-- 里改，改完不用发版：题量、题型、格式要求都在这段文本里。
--
-- ⚠️ **改了这份文本，前端的解析器要跟着看一遍**：
--   题量映射（1-5 单选 … 21-25 面试）在 examParse.js 的 SECTIONS 里也有一份，
--   两边必须一致，否则解析出来的题型和题号对不上。
--
-- ⚠️ **出题规范里那 25 行「考点清单」解析器会直接丢掉**（这是有意的）：
--   清单在第一道 `## 编号` 之前 ⇒ 那时还没有题块可归 ⇒ 整段忽略。
--   它的作用是让模型**先规划再写**，从而 25 道题不重复（同一个概念只考一次）。
--   ⚠️ 所以清单里**不许出现 `##` 标题**（`## 1 xxx` 会被当成第 1 题的题头）。
--
-- ⚠️ **这两段文本里不能出现【引用】/【判据】/【格式】**：
--   那三个标记会让后端把文本按「判据 / 格式」分节重排（composeInstruction）。
--
-- 【为什么节点和值放一个脚本】
-- 考试是 demo，要能**整块拔掉**：节点 + 值 + 前端两个文件 + 路由 + 入口按钮
-- 是同一件事，散在两个 SQL 文件里就不好拔。

-- ============================================================
-- 1. 配置树：AI 提示词下并列一个「考试」分组
-- ============================================================
-- 位置：ai.prompt.exam（和 ai.prompt.question「引导问题」并列）。
--
-- ⚠️ **不在 ai.prompt.question 下面**：那一组的前缀是引导问题列表
--    （/ai/questions 按前缀取叶子 ⇒ 每个叶子都变成抽屉里的一个按钮）。
--    挂进去，考试的两个规范会变成两个引导问题按钮。

INSERT INTO `sys_config_node` (parent_id, name, code, config_key, sort, remark)
SELECT p.id, '考试', 'exam', 'ai.prompt.exam', 3, '考试模式（demo）的出题与判分规范'
FROM `sys_config_node` p
WHERE p.config_key = 'ai.prompt'
  AND NOT EXISTS (
    SELECT 1 FROM (SELECT * FROM `sys_config_node`) x WHERE x.config_key = 'ai.prompt.exam'
  );

INSERT INTO `sys_config_node`
  (parent_id, name, code, config_key, value_type, sort, remark)
SELECT p.id, n.name, n.code, CONCAT(p.config_key, '.', n.code), 'text', n.sort, n.remark
FROM (
  SELECT '出题规范' AS name, 'paper' AS code, 1 AS sort,
         '出题规范模板：只写「怎么写题」。题量 / 难度 / 附加要求由下面三个配置项单独控制' AS remark
  UNION ALL
  SELECT '判分规范', 'grade', 2,
         '交卷时整份发给模型：判定只有对 / 部分对 / 错，外加逐题讲解'
  UNION ALL
  SELECT '题型与道数', 'types', 3,
         '出卷的题量结构：每行「题型|道数」，题型只能是单选/多选/填空/概念/面试。考试页可以改，默认取这里'
  UNION ALL
  SELECT '难度档位', 'level', 4,
         '难度档位定义：每行「档位名|这个档位考什么」。**第一行是默认档**，考试页的下拉按这个顺序排'
  UNION ALL
  SELECT '考生附加要求', 'extra', 5,
         '考生自己加的一段要求（默认空）。出题时会跟着发给模型，考试页可以改'
) n
JOIN `sys_config_node` p ON p.config_key = 'ai.prompt.exam'
WHERE NOT EXISTS (
  SELECT 1 FROM (SELECT * FROM `sys_config_node`) x
  WHERE x.parent_id = p.id AND x.code = n.code
);

