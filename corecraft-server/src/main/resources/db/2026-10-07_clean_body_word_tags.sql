-- 清理正文词类孤儿标签（2026-10-07）
--
-- ## 为什么删
--
-- 库里的实情（删前）：36 个标签，只有 2 个被复用
--   sql(3)、基本数据类型(2)、12 个恰好 1 次、**22 个一次没用上**。
--
-- 一次性的标签分三类，这次只动其中「本来就不是标签」的那一类：
--
--   1. 命令名 / 参数名 / 状态变量名 —— max_connections、Threads_connected、
--      SHOW STATUS、allowPublicKeyRetrieval。**它们是正文里的字，不是概念。**
--   2. SQL 语法片段 —— order by、唯一字段、连接数。
--   3. 一整句话 —— 「JSON、字符串、对象转换」。
--   4. 症状不是概念 —— 映射失败。
--
-- ## ⚠️ 剩下的 13 个孤儿**故意不删**
--
-- 泛型、Lombok、nacos、HTTP、JAVA、JDBC、计算机网络、测试、有参构造、
-- 无参构造、数据库连接、排序、MySQL —— 这些是**像样的概念标签，只是暂时没人用**。
-- 删了等于丢词表：以后有知识涉及「泛型」时没词可挑，模型只能再造一个。
-- **词表是资产，垃圾标签才是垃圾。**
--
-- ## 这些孤儿是怎么攒出来的（机制问题，没在这次修）
--
-- `updateTopic` 对 tags 只做 `deleteByTopicId` 删关联，**不回收没人用的 kp_tag 行**。
-- 所以「摘掉一条知识的最后一个标签」之后，标签主表那行永远留着，标签下拉里
-- 还照常列得出来（显示 0）。孤儿就是这样一个个攒出来的。
--
-- ## 删除带了守卫
--
-- `AND NOT EXISTS (... FROM kp_topic_tag ...)`：万一这期间哪个标签被用上了，
-- 它不会被删掉。执行前 9 个的用量都复核过是 0，执行后关联行数 17 一条没少。
--
-- 回滚见文件末尾，id 都在。
-- ============================================================

DELETE t FROM `kp_tag` t
WHERE t.id IN (15,19,26,27,28,29,30,32,36)
  AND NOT EXISTS (SELECT 1 FROM `kp_topic_tag` tt WHERE tt.tag_id = t.id);


