-- 知识点正文提示词 v4.5：授权更丰富的表达形式（表格 / 列表 / 代码块 / 引用 / 官方参考链接）
-- 2026-10-24
--
-- 背景：用户指出"生成的内容有表格和无序列表"（事实），并问"这个的提示词是放在配置么"，
--   希望"知识确实涉及的情况下"可以用更能体现的表达方式。
--
-- 事实基础（本轮读代码查过的，不是猜的）：
--   · 渲染层**已经支持**表格 / 列表 / 代码块 / 引用 / 链接
--     （详情页正文走 Milkdown = commonmark + gfm preset）⇒ 授权它们零代码成本。
--   · **图片**：kbImageNode 确实注册了，但**没有加载失败处理** ⇒ 模型编的地址
--     会渲染成坏图 ⇒ 提示词里禁掉。
--   · **流程图**：全站**没有 mermaid 依赖**（package.json 只有 core/commonmark/gfm/listener/vue）
--     ⇒ 同样禁掉。
--   · **外部链接不做校验**（用户明确："模型写什么存什么"）⇒ 系统侧不建白名单，
--     只在提示词里要求"地址写你确实知道的官方地址，没把握就只写文档名称"。
--
-- ⚠️ **加代码块必须同时加一条硬约束**：解析器 `parsePoints` 按**行首 `## `** 切知识点
--   （utils/knowledgePoints.js:55）⇒ 代码块里出现 `#` 开头的行会被当成新知识点，
--   把一条切成两条。所以提示词里写死"代码块里不要出现以 `#` 开头的行"。
--   （这属于"解析器靠标记推断 ⇒ 规范必须写明同一个标记"那条老教训。）
--
-- 改的是**提示词**，不是解析器 ⇒ 只改配置即可，不用发版。
-- 执行时机：随时（只动 corecraft 库）。


-- ========== ① 跑前自检（应当输出 1 行，长度 1314 = v4.4）============
SELECT id, config_key, CHAR_LENGTH(config_value) AS len
  FROM corecraft.sys_config
 WHERE config_key = 'ai.prompt.knowledge.point';


-- ========== ② 改成 v4.5 ==========
UPDATE corecraft.sys_config
SET config_value = '给一个目录写它下面的知识点正文。

材料里给了：**主题**、**目录路径**、**这个目录现有的子目录**、**这个主题下已经写过的知识点标题清单**。可能还给了**这次要写的知识点标题清单**，以及**这个目录下面的章节和它们各自的知识点**（总览知识点要用；章节后面带地址的，把章节名写成链接）。

**给了标题清单**时：
- 标题照抄清单里的，不要改写、不要合并、不要拆。
- **按清单给的顺序输出，一条都不能少，顺序不许自己调换。**

**没给标题清单**时：先自己定这个目录该有的 3 到 5 个知识点标题，再按同样的格式写正文。

每个知识点写成一条独立的知识：
- **标题就是术语名词**（清单里是什么就用什么），不要写成陈述句
- **正文靠你自己的知识写**：材料只告诉你"写哪个知识点"（标题）和"放在哪个目录"，**不会给你内容** —— 定义、原理、特点、应用都要你自己写出来
- **正文是 markdown，500 到 900 字**
- **正文按五段写，小标题带序号、名字要规范**（像书里的目录）：
  1. `### 1. 定义`：一句话说清定义、全称、所属领域
  2. `### 2. 原理`：机制、流程、关键步骤；**列成要点清单**
  3. `### 3. 特征与对比`：它自己的特点；和相近概念的区别（**用表格对比**）
  4. `### 4. 应用`：真实工程里怎么用、典型场景、注意事项（后端/云原生视角）
  5. `### 5. 常见考点`：这个知识点最常被考的点、容易记错或答错的地方，以及可能的问法 + 一句话答案
  **五段都要写**，写不出来就写你确实知道的那部分，不要留空
- **小标题一律用 `###` 开头**（`##` 是知识点的分隔标记）；**要再往下拆一层时用 `####`**（例如「2. 原理」下面有多个子机制，就拆成 `#### 2.1 进程调度`、`#### 2.2 上下文切换`）
- **表达形式按内容选，不要写成大段散文**：
  - **列表**：能列举的用 `- `（有先后顺序用 `1. `）
  - **表格**：能对比的用 markdown 表格（至少两列：项目 / 要点）
  - **代码块**：命令、配置、代码、伪代码用 ``` 代码块并标上语言
  - **引用**：原文定义、标准条款、官方说法用 `> ` 引用块
  - **参考链接**：官方文档 / 权威来源可以在末尾用 markdown 链接（`[文档名](地址)`）；地址写你确实知道的官方地址，没把握就只写文档名称
- **表格和代码块别滥用**：一个知识点最多一两个表格；代码块只放真需要逐行看的东西
- **代码块里不要出现以 `#` 开头的行**（`#` 是标题标记，会把这条知识点切碎）
- **不要写图片和流程图**（地址基本都是编的，渲染层也画不了）
- **不要写"这份内容里没写""材料没有给出"这类话** —— 材料本来就只给标题，内容是你的活
- **要有具体的结论**：能对比就对比、能举例就举例、能量化就量化
- 不要写"学习路线""本章小结""欢迎交流"这类废话
- **不要和这个目录现有的子目录重复**（子目录已经覆盖的领域就别在这里再写）
- 不要和清单里其他知识点写重复的内容；**已经写过的不要再写一遍**
- **总览知识点**（材料里给了下级章节和它们的知识点时）：正文写成这个主题/模块的**索引** —— 它讲什么、分成哪几个章节、每个章节讲什么、重点和难点在哪，并把下级章节和知识点的名字列出来
- **总览知识点里提到下级章节时，章节名写成 markdown 链接**：材料里给了地址就照抄（`[章节名](地址)`）；没给地址就写普通文字，**不要自己编地址**

格式：每个知识点一段，段与段之间空一行：
## <知识点标题>
<正文>'
WHERE user_id = 0 AND config_key = 'ai.prompt.knowledge.point';


-- ========== ③ 跑后校验（每条都应当是 1）============
-- 新增的五种表达形式都在：
SELECT
  CHAR_LENGTH(config_value)                                              AS len,
  config_value LIKE '%**代码块**%'                                        AS 有代码块,
  config_value LIKE '%**引用**%'                                          AS 有引用,
  config_value LIKE '%**参考链接**%'                                      AS 有参考链接,
  config_value LIKE '%代码块里不要出现以 `#` 开头的行%'                    AS 有代码块护栏,
  config_value LIKE '%不要写图片和流程图%'                                AS 禁图片流程图,
  config_value LIKE '%五段都要写%'                                        AS 保留五段结构
  FROM corecraft.sys_config
 WHERE config_key = 'ai.prompt.knowledge.point';


