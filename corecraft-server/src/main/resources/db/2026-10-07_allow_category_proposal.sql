-- ============================================================
-- 目录政策：从「只能从清单里选」改成「允许提议 + 确认才建」（2026-10-07）
--
-- ## 原来那句话是废话
--
-- pick_category 的描述写着「只能从清单里选，不要自己造名字。都不合适就回答
-- 「都不合适，建议新建一个」」。模型于是照答这句话，然后：
--
--   matchCategory('都不合适，建议新建一个', 清单) → 匹配不上
--   → 落进 unmatched 分支
--   → 界面显示：AI 推荐「都不合适，建议新建一个」，现有目录里没有这个名字。
--
-- **等于什么都没告诉用户。** 那句话本来是给模型看的"这里需要新建"，
-- 但代码里没有任何一处接它。
--
-- ## 为什么不直接改成「随便造名字」
--
-- 目录会爆炸。库里已经有 `Mybatis` 了，模型很可能再造一个 `MyBatis`；
-- 已经有 `持久化` 和 `数据库` 了，很可能再造一个 `持久层`。
-- **最后变成每条知识一个目录，等于没有目录。**
--
-- 所以放开的是「**提议**」，不是「**建**」：
--   提示词允许它在都不合适时给一个名字（且先看清单里有没有近义的）
--   界面上这个名字只是下拉里的一个选项「+ 新建目录「X」」
--   **用户点了确认才真的建目录**
--
-- 闸门在人手上，不在提示词里。
--
-- ## 清单其实不薄
--
-- 19 个目录，12 个有知识（数据库 8、Mybatis 5…），7 个是空的
-- （Hashmap / JAVA / 中间件 / 工作 / 操作系统 / 测试 / 集合）——
-- 用户是先搭骨架再往里填。所以「只能从清单里选」这个约束本身不是问题，
-- 真正的问题只是**清单没覆盖时 AI 哑口无言、用户拿不到任何信息**。
--
-- 长度：103 / 247 字符，都 < varchar(255)。⚠️ **再往里加内容必须先重新量。**
-- ============================================================

UPDATE `sys_dict_item` SET `remark` = '这条知识该归到哪个目录。优先从下面这份目录清单里挑最贴切的一个，原样输出它的名字。
都不合适时，给出你认为最合适的一个新目录名（4 个字以内）。提之前先看清单里有没有近义的，有就归过去，别造一个几乎一样的。'
WHERE `dict_type_id` = (
  SELECT id FROM `sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `value` = 'pick_category:categories' AND `is_delete` = 0;

UPDATE `sys_dict_item` SET `remark` = '这条知识还没起名字、没归类、没打标签。一次给全，严格按下面三段输出，除此之外不要写任何解释：
名字：<12 个字以内，说清它讲的是什么，不要用「详解」「介绍」这类空词>
目录：<优先从清单里挑最贴切的，原样输出名字；都不合适就给一个你认为合适的新目录名（4 字以内），先看清单里有没有近义的>
标签：
- <这条知识「涉及」的概念，0 到 4 个。换个知识点它还成立吗？只在这条里成立的是正文不是标签。目录管「属于哪个」、标签管「涉及什么」，目录叫「Java›泛型」就别再打「泛型」。宁缺毋滥>'
WHERE `dict_type_id` = (
  SELECT id FROM `sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `value` = 'organize:categories,tags' AND `is_delete` = 0;
