-- ========== ① 骨架规范 ==========
UPDATE corecraft.sys_config
SET config_value = '把一个主题拆成一套能照着学的目录树，每个章节下列上这个领域该掌握的知识点。**只输出目录树，不要任何解释、不要开场白。**

材料里给了**主题**，可能还有**现有目录清单**。
- 清单**只用来避开重复造同义目录**（清单里已有「集合」，就别再起一个「集合」）
- 输出的树**自成一体**，全部是新的，**不要挂到清单里的任何目录下**

层级（**照经典教材的样子：篇 → 章 → 节，不许跳**）：
- 第 1 层：**主题目录**（书名，如「操作系统」）
- 第 2 层：**模块目录**（书里的"篇"，如「2. 进程管理」）
- 第 3 层：**章节目录**（书里的"章"，如「2.1 进程基础」）
- 叶子：**知识点标题**（书里的"节"，挂在章节目录下面）

每一层放什么（**按书的惯例**）：
- 模块 = 一个**大领域**（进程管理 / 内存管理 / 文件系统 / I/O 与设备 / 安全与虚拟化），**5 到 8 个**
- 章节 = 这个领域里的**一个问题域**（进程基础 / 线程 / 调度 / 同步与互斥 / 死锁与通信），**3 到 5 个**
- 知识点 = 该问题域里的**一个具体概念或机制**（PCB / 进程上下文切换 / 时间片轮转），**3 到 5 个**
- **知识点总数不超过 120 条**

命名（**都要是名词短语：不要句子、不要问题、不要口水话**）：
- **模块带序号「2.」、章节带序号「2.1」**；主题目录不带序号（它是书名）
- **章节名是领域名**：「进程基础」「调度算法」「死锁的四个必要条件」；**不要**「进程是什么」「进程的定义」「进程概述」「进程简介」
- **知识点名是标准术语或名词短语**：「进程上下文切换」「PCB（进程控制块）」「进程终止」「内核态与用户态」「银行家算法」；**不要**陈述句（「进程上下文切换需要保存寄存器」「进程终止会释放所占资源」）
- **不要「XX的定义」「XX的含义」「XX是什么」「XX概述」**：直接写术语（**「的」也不留**：「操作系统的定义」→「操作系统定义」，「进程的作用」→「进程作用」）
- 名字要能当**检索词**、能当**卡片标题**；结论、原理、对比写进正文
- 目录名不超过 50 个字

总览知识点：
- **凡是下面还有子目录的那一层（主题、模块），自己也要有一个知识点**，写成这个目录的**第一个子条目**（和下级目录平级），是**总览**：这个主题/模块讲什么、包含哪几个下级目录、各自的重点
- **章节下面只有知识点，不需要总览**
- **总览知识点的名字要能独立说清这一层讲什么**（「操作系统基础总览」「进程与线程总览」）；**不要在层名后面堆词**（「操作系统概述导览」这种不要）

结构例子（**照这个层次来，内容换成主题自己的**）：
计算机网络
├── 计算机网络总览
├── 1. 物理层
│   ├── 物理层总览
│   ├── 1.1 传输介质
│   │   ├── 双绞线
│   │   └── 光纤
│   └── 1.2 信道容量
│       ├── 奈奎斯特准则
│       └── 香农定理'
WHERE user_id = 0 AND config_key = 'ai.prompt.knowledge.outline';


