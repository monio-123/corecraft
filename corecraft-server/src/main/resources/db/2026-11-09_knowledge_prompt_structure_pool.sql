UPDATE `corecraft`.`sys_config`
SET `config_value` = REPLACE(
      `config_value`,
      '- **正文分段：两段必写，三段按需**（小标题带序号、名字要规范，像书里的目录）：
  - **必写 ① `### 1. 定义`**：一句话说清定义、全称、所属领域，再补一句它的边界（跟什么不是一回事）
  - **必写 ② `### 2. 原理`**（机制 / 依据 / 展开）：它到底怎么成立的、关键步骤或判据；**列成要点清单**
  - **按需 ③ `### 3. 特征与对比`**：它自己的特点；和相近概念的区别（**用表格对比**）
  - **按需 ④ `### 4. 应用`**：真实工程里怎么用、典型场景、注意事项（后端/云原生视角）
  - **按需 ⑤ `### 5. 常见考点`**：这个知识点最常被考的点、容易记错或答错的地方，以及可能的问法 + 一句话答案
  - **按需的那三段，不适用的就整段跳过，不要硬凑**（法律条文、哲学概念、纯历史事件本来就没有「特征与对比」）。**跳过的段不占号**：写了哪几段就按顺序编 1、2、3…',
      '- **正文分段：前两段必写，其余从段落池里挑**（小标题带序号、名字要规范，像书里的目录）：
  - **必写 ① `### 1. 定义`**：一句话说清定义、全称、所属领域，再补一句它的边界（跟什么不是一回事）
  - **必写 ② `### 2. 原理`**（机制 / 依据 / 展开）：它到底怎么成立的、关键步骤或判据；**列成要点清单**
  - **段落池（判据在先：不满足就不写这一段；从里面挑 1 到 3 段，按顺序接着编号）**：
    - `### 3. 特征与对比` —— **有至少一个相近概念、且区别是理解它的关键**时才写（**用表格对比**）
    - `### 4. 组成与结构` —— 它**由多个部件构成、或本身有层次**时才写（讲清每部分干什么）
    - `### 5. 应用` —— **有真实工程 / 使用场景**时才写（后端/云原生视角、注意事项）
    - `### 6. 演进与历史` —— 版本变迁或来龙去脉**本身就是理解它的重点**时才写
    - `### 7. 常见考点` —— 这个概念**会出现在考试 / 面试里**才写；它是出题的素材，**技术类默认写**（最常考的点、容易记错或答错的地方、可能的问法 + 一句话答案）
  - **段名可以按内容微调**：讲"两种实现的差异"就写 `### 3. 两类实现的差异`，讲生命周期就写 `### 3. 生命周期` —— 但必须带序号、必须是个能讲的内容块（不要"关于 XX 的说明"这种空壳）
  - **跳过的段不占号**：写了哪几段就按顺序编 1、2、3…；**一条判据都不满足就只写 1、2 两段**，两段本身就完整（法律条文、哲学概念、纯历史事件常常只有两段）—— **不要为了"看着齐全"硬加段**'
    )
WHERE `user_id` = 0
  AND `config_key` = 'ai.prompt.knowledge.point'
  AND `config_value` LIKE '%- **正文分段：两段必写，三段按需**%';

