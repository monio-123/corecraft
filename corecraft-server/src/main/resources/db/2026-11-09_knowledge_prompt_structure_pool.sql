-- ============================================================
-- 2026-11-09 知识点正文提示词：段落池判据化 + 图型选型线索 + 提示块授权
--
-- ## 为什么要改（查库实测，不是猜的）
--
-- 实测对象：2026-11-09 当天生成的两个主题（JAVA 基础 id=1211 / 24 条；
-- 操作系统 id=1204 / 22 条）：
--
--   · 段 1 定义 / 段 2 原理：100% / 100%
--   · 段 3 特征与对比：100% / 95%
--   · 段 4 应用：100% / 95%
--   · 段 5 常见考点：96% / 91%
--   ⇒ 「按需三段」实际命中率 95-100%，**等于五段全写** ——
--     「按需」没有可判定的判据，而技术类知识点对「特征与对比」「应用」
--     永远"适用" ⇒ 模板形同写死，每条知识点长一个样。
--
--   · 带图率：46% / 55%（判据制之前全库 2.5%）⇒ **图的数量问题已经解决**。
--   · 但图型分布：23 张图里 **flowchart 18 张（78%）**，
--     mindmap / timeline / classDiagram / ER 图 **全 0**。
--     ⇒ 提示词列了 8 种图型但不给判断线索，模型默认全用 flowchart
--       （"列清单不给判据"的现成反面教材）。
--
-- ## 改三处（都在 ai.prompt.knowledge.point 同一份 config_value 上，一次改完）
--
-- ① **三段按需 → 段落池 + 判据**：除了原来的三段，把「组成与结构」「演进与历史」
--    补进池子（原来讲"由哪些部件构成""版本怎么变的"没地方放，只能硬塞进「原理」）；
--    每段配一句**可判定的触发条件**；并允许段名按内容微调（讲生命周期就写「生命周期」）。
--    **不给配额**、不要求"每段都写"——「一条判据都不满足就只写 1、2 两段」。
-- ② **图型选型线索**：不是"内容 → 图型"的映射表（2026-10-28 明确不要那种），
--    只给判断线索（分层 → mindmap / 演进 → timeline / 交互 → sequence /
--    状态 → stateDiagram），并点明 **graph TD 只留给步骤/判断分支**。
-- ③ **提示块授权**：表达形式里加一条 —— 坑、经验、反直觉结论用
--    `> **注意**：…` / `> **易错**：…` / `> **经验**：…` 写。
--    渲染层零改动（就是引用块 + 开头加粗），样式统一在 kb-editor.css；
--    **一条知识最多一个**，没有就不写（守宁缺毋滥）。
--
-- ⚠️ 为什么一次改同一行三处：分三次改会出现"半新半旧"的中间版本，
--    回滚段也会写成三段互相打架的替换（2026-10-25 那次就是这么并成一份的）。
--
-- ⚠️ ai.prompt.edit.body 不动：它是「AI 调整正文」链路，规则是"结构跟着原文走"，
--    没有硬编码五段 ⇒ 原文是段落池结构时它自然跟随。
--
-- 执行时机：一次性迁移（已执行）。改完即时生效，不用发版、不用重启。
-- ============================================================

