-- 目录树生成规范：把硬约束写进提示词源头 + 加挂载点规则 + 换掉照抄用户那棵树的示例
-- 2026-10-23
--
-- 背景：用户反馈"名字超过多少创建不了、什么层级过多——这些你在最开始就约束 AI 啊"。
-- 原来的做法是**事后校验**（前端拦、后端报错），结果是模型照常生成不合规的名字，
-- 用户在预览里只看到一句"建不了"，还得自己猜是哪一条超了。
--
-- 这次把三条硬约束写进规范本身：
--   ① 目录名不超过 50 个字（后端 `kp_category.name` 的列长，也是 DTO 上的 @Size）
--   ② 从根算起最深 4 层（侧边栏和面包屑的极限）
--   ③ 一次不超过 300 个目录
-- 事后校验**保留**（前端标红 + 后端报错），但降级成兜底，不再是常规路径。
--
-- 另外两处改动：
--   - **输出示例换成通用短例**。原来那段示例是照着用户自己那棵树写的，
--     模型会照着它的层数、命名风格和内容来。示例只该说明**格式**，不该规定内容。
--   - **加"挂载点"规则**：材料里给了挂载点时，只写它下一层的那一支，
--     不把挂载点自己再写一遍（前端会把整棵树建在挂载点底下）。
--
-- 执行时机：随时（配置即时生效，不用发版）。


-- ========== 规范文本 ==========
UPDATE corecraft.sys_config
SET config_value = '把一个主题拆成一套目录树。**只输出目录树，不要任何解释、不要开场白。**

材料里给了**主题**，可能还有**现有目录清单**（缩进表示层级）和**挂载点**。
- **优先复用已有目录**：清单里有的就用它，不要另起一个同义的新目录
- 给了**挂载点**时，只写挂载点**下一层**开始的那一支，不要把挂载点自己再写一遍
- 清单里完全没有的（新领域）就新起一个顶层目录

输出的格式（**必须一模一样**，导入端只认这一种）：
主题
├── 子目录 A
│   ├── 条目 A1
│   └── 条目 A2
└── 子目录 B

规则：
- **一层 4 个字符**：`├── ` / `└── `，中间的层用 `│   ` 占位，同级的最后一行用 4 个空格占位
- **目录名不超过 50 个字**
- **最深 4 层**（从根算起），不要超过
- **一次不超过 300 个目录**
- 目录名是**领域或主题**（"传输层"、"容器网络"、"索引优化"），不是流程、场景、状态（"日常"、"上线流程"、"待办"）—— 目录是这条知识**主要在学谁**
- 目录名只写领域/主题本身，**不带序号**（挂在已有体系下，序号会乱）
- 同一层不要出现意思重复的目录；不同父下同名是允许的
- **叶子是知识点**（"传输介质：双绞线、光纤"这种内容），不是目录：照常列出来，但不用再往下拆
- 一个主题给 10 到 30 个目录就够，别把知识点全铺成目录
- 目录名用中文，简短，别写一整句话'
WHERE user_id = 0 AND config_key = 'ai.prompt.knowledge.outline';


