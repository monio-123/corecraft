-- 2026-10-26 知识点提示词 v3：参考经典教材的讲法 / 放开 mermaid 图 / 知识点之间互相链接
--
-- ## 为什么改（三件事，一次写完）
--
-- 这三条**都改同一份提示词**（`ai.prompt.knowledge.point`）⇒ 一次改、一次落盘。
-- 分三次改同一个键的话，中间那版是半新半旧的，回滚段也会写成三段互相打架的替换。
--
-- ### ① 参考国内外经典教材
--
-- 改之前：outline 侧有「照经典教材的样子：篇 → 章 → 节」「按书的惯例」——
-- 但那里的"书"是**结构比喻**，约束的只是层级形状和命名规范，
-- **没点名任何一本真实书籍**，也没要求内容取材于某本书的论述；
-- point 侧更是一片空白（只有「正文靠你自己的知识写」）。
-- ⇒ 现状是"形似书"，不是"取材于书"。
--
-- 改之后：两条各补一段 —— 章节体系按该主题**公认的经典教材/专著**（中外皆可）的
-- 通行编排来排布；正文按该领域通行教材的**讲法**写（标准叫法 / 常见论证顺序 /
-- 经典对比维度）。
--
-- ⚠️ **护栏：只借鉴结构与讲法，不许写书名、版本、页码、原文引文。**
-- 模型写具体出处几乎一定是编的（"《XX》第 3 章指出……"里书名、页码都是幻觉），
-- 而读者没法分辨 ⇒ 一旦允许写，提示词就等于在生产假引用。
--
-- ### ② 放开 mermaid（原来明令禁止画图）
--
-- 改之前：point 提示词里写着「**不要写图片和流程图**（地址基本都是编的，渲染层也画不了）」。
-- 这条禁令**当时是对的**：渲染层确实画不了（Milkdown 只有 commonmark + linkSchema，
-- 全项目零 mermaid/drawio/svg 支持），图片只能走 `/api/files/` 附件。
--
-- 现在渲染层接上了 mermaid（前端 `components/kbMermaid.js`：语言是 mermaid 的
-- 代码块画成图，源码留在下面可编辑）⇒ 禁令的前提没了，**继续禁着就是白禁**。
--
-- 仍然禁的是**图片**：图片地址模型编不出来，渲染层也不认外链图片。
--
-- ### ③ 知识点之间互相链接
--
-- 改之前：正文里提到别的知识点只能是普通文字（例："InnoDB 中主键决定**聚簇索引**"）。
-- 目录链接倒是有（总览里跳子目录），但那是"从上层跳下层"，用处有限。
--
-- 改之后：模型把相关知识点的名字写成 `[[知识点标题]]`，
-- **落库后由前端统一换成指向那条知识的链接**（`linkTopicMarks`）。
--
-- 为什么是"标记后处理"而不是让模型直接写地址：知识点的 id 是**落库那一刻**才有的，
-- 而正文是落库**之前**写的 ⇒ 模型写正文时不可能知道目标那条的 id。
-- 模型只写名字（它知道名字），地址由系统在整批落库后补上。
--
-- **只标这次生成结构里的**：材料里给了《这次生成结构里的全部知识点》清单，
-- 提示词要求只能标清单里的名字。标错了（不在清单里）系统会把它**退成普通文字**
-- —— 宁可少一个链接，也不要一个点进去是空的。
--
-- 执行时机：一次性迁移（已执行）。
-- ============================================================

-- ------------------------------------------------------------
-- 1. ai.prompt.knowledge.outline：章节体系按公认经典教材排布
-- ------------------------------------------------------------

UPDATE `corecraft`.`sys_config`
SET `config_value` = REPLACE(
      `config_value`,
      '层级（**照经典教材的样子：篇 → 章 → 节，不许跳**）：',
      '**按这个主题公认的经典教材 / 专著来排布**（国内外的通行讲法都行）：章节顺序、每个章节覆盖哪些问题，照通行教材的编排来；不同流派说法有分歧时，取更通用、更接近多数教材的那一种。**只借鉴结构，不要写书名、版本、页码、原文引文**（写了你也编不准）。\n\n层级（**照经典教材的样子：篇 → 章 → 节，不许跳**）：'
    )
WHERE `user_id` = 0
  AND `config_key` = 'ai.prompt.knowledge.outline'
  AND `config_value` LIKE '%层级（**照经典教材的样子：篇 → 章 → 节，不许跳**）：%';


-- ------------------------------------------------------------
-- 2. ai.prompt.knowledge.point：① 讲法 + ② mermaid + ③ 知识点链接
-- ------------------------------------------------------------

-- 2.1 ① 正文按通行教材的讲法写
--
-- 锚点用「定义、原理、特点、应用都要你自己写出来」这一段尾巴：
-- 前半句带中文引号，抄写容易出错（抄错一个字这条就不匹配，affected=0）。
UPDATE `corecraft`.`sys_config`
SET `config_value` = REPLACE(
      `config_value`,
      '定义、原理、特点、应用都要你自己写出来',
      '定义、原理、特点、应用都要你自己写出来
- **按这个领域通行教材的讲法写**：定义用教材里的标准叫法，原理按教材常见的论证顺序展开，对比表按教材里的经典对比维度（不是自己临时想的维度）。**只借鉴讲法，不要写书名、版本、页码、原文引文**（写了你也编不准）。'
    )
WHERE `user_id` = 0
  AND `config_key` = 'ai.prompt.knowledge.point'
  AND `config_value` LIKE '%定义、原理、特点、应用都要你自己写出来%';

-- 2.2 ② 放开流程图 / 时序图 / 状态图（mermaid）
--
-- ⚠️ 围栏语言必须是 `mermaid`：渲染层就是按这个语言认代码块的
-- （前端 `components/kbMermaid.js`）。
UPDATE `corecraft`.`sys_config`
SET `config_value` = REPLACE(
      `config_value`,
      '- **不要写图片和流程图**（地址基本都是编的，渲染层也画不了）',
      '- **流程图 / 时序图 / 状态图用 mermaid 画**：写成 `mermaid` 代码块（语法照 mermaid 官方：`graph TD` / `sequenceDiagram` / `stateDiagram-v2`）；画不出来的结构就老实用步骤清单或表格表达，别硬画
- **不要写图片**（图片地址基本都是编的，渲染层也画不了）'
    )
WHERE `user_id` = 0
  AND `config_key` = 'ai.prompt.knowledge.point'
  AND `config_value` LIKE '%- **不要写图片和流程图**（地址基本都是编的，渲染层也画不了）%';

-- 2.3 ③ 正文里提到别的知识点 ⇒ 写成 [[知识点标题]]
--
-- 放在「总览知识点里提到下级章节时…」那条后面 —— 两条是同一件事的两面
-- （一个是跳目录，一个是跳知识点），放一起模型不容易只学一半。
UPDATE `corecraft`.`sys_config`
SET `config_value` = REPLACE(
      `config_value`,
      '**不要自己编地址**',
      '**不要自己编地址**
- **正文里提到这次生成结构里的另一个知识点时，把它的名字写成 `[[知识点标题]]`**（方括号里只写标题本身，一处提到只标一处）：材料里给了《这次生成结构里的全部知识点》清单的，只能标清单里的名字；没给清单（你自己定标题的那次）就只标你这次写出来的那几条。**不要标清单里没有的名字** —— 标错了系统会把它退成普通文字。'
    )
WHERE `user_id` = 0
  AND `config_key` = 'ai.prompt.knowledge.point'
  AND `config_value` LIKE '%**不要自己编地址**%';


