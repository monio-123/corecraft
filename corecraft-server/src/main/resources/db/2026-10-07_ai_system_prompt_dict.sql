-- AI 统一描述字典（2026-10-07 新增）
--
-- ## 为什么放 sys_dict 而不是继续留在代码里
--
-- 这段描述是**要按反馈反复调的内容**，不是程序逻辑。原来是 AiChatServiceImpl 里的
-- 一个 SYSTEM_PROMPT 常量，改一个字就要改代码 + 重新发版 + 重启后端。
-- 放字典之后改一行 remark 就生效——和引导问题（ai_topic_question）同一套机制，
-- 所以**不新建表、不加列**。
--
-- 和 ai_topic_question 一样是**全局一份**：字典表没有 user_id，描述对所有人一样，
-- 谁也不需要"我自己的那套描述"。要按人隔离的（AI 接口配置）才拆 ai_endpoint。
--
-- ## 三列怎么分工（和引导问题完全一致）
--
--   label   (100) = 后台列表里显示的名字，给人看
--   value   (100) = 机器标识，代码按它取。这里固定 chat（"聊天"这个场景）
--   remark  (255) = **描述正文**，程序原样送进 messages 的 system 角色
--
-- 255 字符够用：当前正文 175 字符 / 503 字节（varchar 按字符计，不按字节）。
--
-- ## ⚠️ 缺了这一项 AI 会直接报错，不是静默降级
--
-- 后端 systemPrompt() 读不到内容就抛异常（AiChatController 捕获后发 error 事件）。
-- **不退回代码常量、也不当空串**：这段描述里最要紧的是"别拿你记忆里的版本替换
-- 用户写的"，悄悄撤掉约束的话模型会立刻自信地编，而且答得看着像模像样、
-- 控制台零报错——比直接失败难查得多。
--
-- 也就是说：这一项被删掉或停用后，AI 问答会**明显坏掉并报错**，这是有意的。
-- ============================================================

