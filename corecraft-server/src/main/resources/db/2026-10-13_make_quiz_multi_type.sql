-- ============================================================================
-- make_quiz 提示词支持多种题型（2026-10-13）
--
-- ⚠️ **2026-10-22：make_quiz 这条引导问题已经整套撤了**（旧自测题那套：
--    题存在库里 + 本地判分 + 每日复习）。出题现在由 `ai.prompt.exam.*` 那组
--    提示词负责（临时考试、AI 判分、题量/难度可配）。
--    本脚本只改**字典**里那一条（早已 is_delete=1，UPDATE 都带 `is_delete = 0`
--    的条件 ⇒ 重放不会动它），**别照着它以为 make_quiz 还活着**。
-- ============================================================================
--
-- ## 要解决什么
--
-- `kp_topic_quiz` 这一轮把题型从「只有单选」扩成 single / multiple / blank / essay，
-- 但**提示词还写着「3 道单选题、每道 4 个选项、其中只有 1 个正确答案」**。
-- 只改列不改提示词，等于把一个只能装单选的柜子换成了四个格子的柜子，
-- 而进货口还只进第一种货——改完功能上线，行为一个字没变。
--
-- 这次的判据是：**题型枚举、`answer` 的列类型、前端解析，三者必须同时到位**，
-- 提示词是其中最容易漏的一环，因为它不在代码里而在字典里，不 grep 代码就看不见。
--
-- ## 三处格式要求各有原因，不是啰嗦
--
-- · 「括号里必须写题型」—— 前端 `parseQuizBlock` 靠 `（多选）` 这类标记判题型，
--   没有标记时退化成「按答案有几个字母反推」，多选题只标一个正确项。
-- · 「简答要点用 `- `，不要用 `1. 2.`」—— 前端 `splitQuizBlocks` 是按「行首是编号」
--   切题的（`## 题目 1` / `1.` / `1、` 都收）。简答要点真写成编号列表，
--   **一个要点会被切成新的一题**，前半截解析成半道题，整份直接不采纳。
--   `- ` 开头不在切题正则里，是唯一安全的列表写法。
-- · 「要点加起来不超过 60 字」—— `answer` 列是 VARCHAR(100)，MySQL 严格模式下
--   超长直接报错、整次采纳失败；非严格模式下被截断，答案半句没尾。
--   这条写进提示词，是让模型在源头就别写超。
--
-- ## 媒体怎么带
--
-- 题目走 markdown，`![](链接)` 直接嵌图，不再为图片单开一个字段
-- （图片只是题干的一部分，主体的仍然是题干文字）。
-- 提示词里明确限定「只有当图片本身是理解那道题的前提时才嵌」——
-- 现在的笔记库里没有任何图片，模型没有可引用的真实链接，
-- 不设这道闸就是拿编造的 URL 凑数。
--
-- ## 为什么仍然不套 【判据】/【格式】 标记
--
-- `AiChatServiceImpl.composeInstruction` 的注释里已经定了调：
-- 「没标记就整段原样用（向后兼容）：make_quiz 这类本来就没有可复用的判据，
-- 不该为了格式统一给它们硬套标记」。这里照办。
-- 真出现第二条要复用出题判据的提示词（批量出卷）时再加标记，那时判据才真的有两个归属。
--
-- ## 题干必须自足（2026-10-14 实测补的）
--
-- 第一版判据里写的是「题干给一个具体场景（哪段代码、什么现象、什么需求）」。
-- **模型把「给一个场景」理解成了「先铺一个引子」**，于是出出来的是
--
--   「你想按笔记里的方法来修复 DNS 未响应，已经在「运行」框里输入了 cmd……」
--   「有人打算照方法一处理。下列关于这套流程的说法……」
--
-- 前者依赖的是这份笔记，后者依赖的**还不只是笔记，还依赖前一道题**——
-- 读者手上只有一道题时，这两句话都不成立。题目要能独立存在，引用的是知识点概念本身，
-- 不是这份知识点的场景和叙述。
--
-- 所以判据从「给一个具体场景」改成**正面写清自足性**：不许出现哪类指代、
-- 不许铺垫哪类引子、不许把笔记的段落整段抄进题干。
--
-- 顺带治了另一个真问题：第一版模型会**在题目前面把整段笔记正文复述一遍**
-- （「方法一：刷新DNS缓存」「依次执行以下命令」…）。那份输出恰好会被解析器兜住——
-- 复述段自己成了第一个题块、没有选项，`parseQuizBlock` 返回 null、整份不采纳，
-- 界面上报「没能解析成可采纳的值」。**是"报错"而不是"静默写进库"**，
-- 但用户拿到的是三道好题被自己的开场白拖累，所以格式段补了一条「直接输出三道题」。
--
-- ## 关于库名
--
-- 显式带 `corecraft`，免得在别的会话里跑、一条 UPDATE 打到 `sys` 库去还照样成功。
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1/2  make_quiz —— 改成四种题型，给出可解析的格式约定
-- ----------------------------------------------------------------------------
UPDATE `corecraft`.`sys_dict_item` SET `remark` = '基于这条知识出 3 道题考读者，题型必须多样：1 道单选、1 道多选、1 道填空或简答（这条知识更适合哪一种就出哪一种）。

格式：
- 题头写成 ## 题目 1（单选），括号里的题型必须写出来：单选 / 多选 / 填空 / 简答
- 选择题每个选项单独一行，前面是字母加一个点：A. 内容。单选 4 个选项、只有 1 个正确；多选 4 个选项、至少 2 个正确
- 答案单独一行，写作「答案：」。单选写一个字母；多选把所有正确字母连着写（答案：AB）；填空写那个词
- 简答的答案写在「答案：」下面另起行，每条要点前面加 "- "。不要用 1. 2. 这样的编号，会被当成新的一题
- 简答要点每条不超过 40 字，全部加起来不超过 60 字
- 直接输出三道题，不要在前面复述笔记内容、不要加开场白或小结

每道题必须能单独存在：读者手上只有这道题，没有笔记、没有前一道题、也没有「某人」。
- 把要考的概念本身写进题干，不要铺垫「某人正在按笔记做某事」这种引子
- 不许出现「笔记里」「按笔记」「上面提到的」「方法一」「本文」「前文」这类只有看过原文才懂的指代
- 不要把笔记的段落、标题、命令清单整段抄进题干。笔记是出题素材，不是题干本身
- 概念题直接问概念，场景题直接给场景条件，两者都不要再包一层来历交代

题目要能脱离笔记独立答对，读者靠的是回忆和应用，不是辨认：
- 选择题的选项是不同的理解或做法，成立的那些才是正确项；不要把笔记里并列写的几行拆开当选项
- 3 道题考 3 个不同的点，不要是同一件事的措辞变化
- 只有当图片本身是理解那道题的前提时，才在题干里用 markdown 嵌一张图：![这张图说明什么](图片链接)。不要为了好看加图'
WHERE `dict_type_id` = (
  SELECT id FROM `corecraft`.`sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `value` = 'make_quiz:none' AND `is_delete` = 0;


-- ----------------------------------------------------------------------------
-- 2/2  核对：应该只有这 1 行受影响，且开头是「基于这条知识出 3 道题」
-- ----------------------------------------------------------------------------
SELECT `id`, `value`, CHAR_LENGTH(`remark`) AS len, LEFT(`remark`, 40) AS head
FROM `corecraft`.`sys_dict_item`
WHERE `value` = 'make_quiz:none' AND `is_delete` = 0;


