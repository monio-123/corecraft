-- ## 缺口 ① 「一整句话」这一类反例漏了
--
-- skill §2.2 判据第 1 步列了三类不是标签的东西：
--   参数值（max_connections）· 命令（SHOW STATUS）· **一整句话**（「JSON、字符串、对象转换」）
--
-- 提示词里只有前两类。第三类**真实发生过**——那个 `JSON、字符串、对象转换` 就是 #84
-- 用户指着截图说「感觉很难在其他的笔记中也能找出来」的一批，#91 又来了一次
-- （模型把理由写进目录名）。**而且它是最难识别的一类**：看起来像个标签，
-- 其实是正文的一句话。缺了防不住。
--
-- ## 缺口 ② 没有禁止「提迁移建议」——**新判据带来的新风险**
--
-- #94 改成"允许目录级概念当标签"之后，模型会看到：清单里已有 `MySQL` 目录，
-- 而它这一轮又要输出 `MySQL` 标签。它可能想「那应该迁过去」——
-- 然后把这半句写进输出。解析器要么忽略、要么**当成目录名建进去**，
-- 这正是 #91 那个脏目录 `JDBC（清单里没有近义项，建议新增；退一步可归「数据库」）`
-- 的来路。
--
-- 原来的「不要写理由」只覆盖了一部分，没点名这个具体场景。补成：
--   「不要提「建议迁到某个目录」——目录和标签各管各的，这一栏只填名字。」
--
-- ## 长度：288 / 386 / 488，都远 < varchar(1000)（#88 扩的列）
-- ============================================================

UPDATE `sys_dict_item` SET `remark` = '这条知识该归到哪个目录。

判断标准：这条知识主要在学谁，就归谁。
- 「MyBatis 一对多映射的分页」主要在讲 MyBatis → 目录 MyBatis；顺带涉及的 MySQL 写进标签
- 「MySQL 连接数怎么看」主要在讲 MySQL → 目录 MySQL
- 成套知识体系的概念（泛型、序列化）通常就是主归属

清单里有合适的就选最贴近的那一层，有更具体的别选更宽的。
要新建就用斜杠写出它该挂在哪下面：挂「数据库」下面的新目录写「数据库/MySQL」。
只输出路径本身。不要写理由、不要加括号、不要提「建议迁到某个目录」——目录和标签各管各的，这一栏只填名字。'
WHERE `dict_type_id` = (
  SELECT id FROM `sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `value` = 'pick_category:categories' AND `is_delete` = 0;

UPDATE `sys_dict_item` SET `remark` = '这条知识涉及哪些概念——主归属之外的那些。

主归属已经在目录里了，标签装的是剩下的。目录只能选一个，所以一条知识同时涉及好几个有体系的东西时，题目主要在讲哪个归哪个目录，其余的——哪怕它本身也是个正经的技术栈（一条讲 MyBatis 的笔记顺带说了 MySQL 的分页，MySQL 就写在这儿）——都放到标签里。

不是标签的是正文：具体的参数值（max_connections）、命令（SHOW STATUS）、一整句话（「JSON、字符串、对象转换」——那是一条知识的标题，不是标签）。
粒度要说清是哪种：「排序」太笼统，分不清是数据库里排、Java 对象里排还是 List 里排。

数量 0 到 4 个，宁缺毋滥。凑出来的标签是垃圾，比没有还糟。
下面的清单只是「你已经用过哪些叫法」，用来统一叫法，它不是推荐清单。
每行只写标签名本身，不要写理由、不要加括号。'
