--       卡片网格 / 拖拽归类），顶部的录入框已收归首页，这一页改成纯浏览页，
--       原名「随手记」名不副实。
--
-- ⚠️ 这条只改侧边栏显示名（sys_permission.name）。顶栏 / tab 标题走的是
--    router/index.js 里的 meta.title，前端代码已同步改成「知识点」，
--    两边必须一起改，只改一边会出现侧边栏叫「知识点」而顶栏还叫「随手记」。
--
-- 按 skill 的数据库强约束：菜单配置属于配置而非代码，优先在管理后台「资源管理」
-- 里改；本脚本是给不方便开后台时的等价替代，同样由用户手动执行，agent 不代跑。
--
-- 定位方式用 code 而不是 id：id 是自增值，跨环境（dev / test / prod）不一致，
-- code 才是稳定的业务标识。加 is_delete = 0 守门，避免误改已软删的历史记录。
-- ============================================================================

UPDATE sys_permission
SET name = '知识点'
WHERE code = 'corecraft-web:learn'
  AND is_delete = 0;
