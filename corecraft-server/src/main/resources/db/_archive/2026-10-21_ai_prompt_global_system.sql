-- ============================================================================
-- AI 提示词：场景轴 → 全局人设（一次性迁移，2026-10-21）
--
-- ## 为什么要改
--
-- 原来「场景统一描述」这条轴长这样：
--
--   ai.prompt.system            （分类：场景统一描述）
--   └── ai.prompt.system.chat   （叶子：问答统一描述）
--
-- 前端每个提问带一个 scene，后端按 `ai.prompt.system.<scene>` 取那段描述。
-- **全站只传过 'chat' 一个值**（3 个调用点都写死），6 条引导问题 + 用户自由提问共用它。
--
-- 问题不在"少传了一个值"，在于**那段描述是问答口吻**：
--
--   "用户会就一条知识提问。分两种情况回答：问的是这条知识写了什么……"
--
-- 而它被当作 role=system 发给了**命名、选目录、选标签、出题、整理**这些根本不是
-- "提问"的任务。轴是假的（只有一格），描述和用途也对不上。
--
-- ## 改成什么
--
--   ai.prompt.system   （叶子：全局人设，直接挂在「AI 提示词」下）
--
-- 一段粗略描述"这个系统是什么、回答长什么样"的文字，**所有任务共用**；
-- 各任务自己的规则一律放引导问题里（**一条规则只有一个归属**）。
--
-- ## 顺带把出题提示词改成"素材无关"
--
-- 出题原先写死"基于这条知识出 3 道题"，素材只能是这条知识点自己的正文。
-- 现在素材是一个参数（前端可以传一段用户自己粘的文字），
-- 所以提示词里"这条知识 / 笔记"的说法要改成"上面给的内容"。
--
-- ⚠️ **"内容"和"材料"两个标签是后端拼的**：
--   没传素材 → "标题：X\n\n内容：\n<这条知识的正文>"
--   传了素材 → "材料：\n<用户粘的那段文字>"
-- 提示词里统一说"上面给的内容"，两种都盖得住。
--
-- ## 关于库名
--
-- 显式带 `corecraft`，免得在别的会话里跑、一条 UPDATE 打到 `sys` 库去还照样成功。
--
-- ## ⚠️ 这份文字在两个文件里各有一份
--
--   本文件（_archive/，给**现库**跑，一次性）
--   2026-10-21_sys_config_node_tree.sql（初版脚本，给**重置**用）
--
-- 改措辞时两个都要改。
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1/4  全局人设：键改名 + 换成新的正文
-- ----------------------------------------------------------------------------
-- 键从 ai.prompt.system.chat 改成 ai.prompt.system（没有场景这一段了）。
-- 唯一键是 (user_id, config_key)，新键不存在，改名不撞键。
UPDATE `corecraft`.`sys_config`
SET `config_key` = 'ai.prompt.system',
    `config_value` = '你是一个学习助手，服务于一个自主学习平台：用户在这里记录和整理知识点，给知识点归类、打标签，基于知识点出练习题，也会就某个知识点的内容向你提问。
你的回答只依据这次给你的内容，不要拿你记忆里的版本替换它；内容里没写到的地方，明说「这份内容里没写」，不要自己补。
直接给结果：不要复述任务、不要解释你正在做什么、不要写「好的」这类开场白。',
    `remark` = '全局人设：所有任务共用的一段系统描述'
WHERE `user_id` = 0 AND `config_key` = 'ai.prompt.system.chat';


-- ----------------------------------------------------------------------------
-- 2/4  出题提示词：改成素材无关的说法
-- ----------------------------------------------------------------------------
-- 变的是"素材是谁"这件事：
--   基于这条知识出 3 道题        → 基于上面给的内容出 3 道题
--   （这条知识更适合哪一种…）    → （这段内容更适合哪一种…）
--   复述笔记内容                → 复述内容
--   没有笔记、没有前一道题        → 看不到上面的内容，也没有前一道题
--   某人正在按笔记做某事         → 某人正在做某事
--   笔记是出题素材              → 内容是出题素材
--   脱离笔记独立答对            → 脱离原文独立答对
--   笔记里并列写的几行          → 内容里并列写的几行
--
-- 「不许出现『笔记里』『按笔记』…」那条**保留**：那是"只有看过原文才懂的指代"
-- 的举例，不是"素材必须是笔记"的要求。素材是粘贴的文字时它用不上，用不上也无害。
UPDATE `corecraft`.`sys_config`
SET `config_value` = '基于上面给的内容出 3 道题考读者，题型必须多样：1 道单选、1 道多选、1 道填空或简答（这段内容更适合哪一种就出哪一种）。

格式：
- 题头写成 ## 题目 1（单选），括号里的题型必须写出来：单选 / 多选 / 填空 / 简答
- 选择题每个选项单独一行，前面是字母加一个点：A. 内容。单选 4 个选项、只有 1 个正确；多选 4 个选项、至少 2 个正确
- 答案单独一行，写作「答案：」。单选写一个字母；多选把所有正确字母连着写（答案：AB）；填空写那个词
- 简答的答案写在「答案：」下面另起行，每条要点前面加 "- "。不要用 1. 2. 这样的编号，会被当成新的一题
- 简答要点每条不超过 40 字，全部加起来不超过 60 字
- 直接输出三道题，不要在前面复述内容、不要加开场白或小结

每道题必须能单独存在：读者手上只有这道题，看不到上面的内容，也没有前一道题、也没有「某人」。
- 把要考的概念本身写进题干，不要铺垫「某人正在做某事」这种引子
- 不许出现「笔记里」「按笔记」「上面提到的」「方法一」「本文」「前文」这类只有看过原文才懂的指代
- 不要把内容的段落、标题、命令清单整段抄进题干。内容是出题素材，不是题干本身
- 概念题直接问概念，场景题直接给场景条件，两者都不要再包一层来历交代

题目要能脱离原文独立答对，读者靠的是回忆和应用，不是辨认：
- 选择题的选项是不同的理解或做法，成立的那些才是正确项；不要把内容里并列写的几行拆开当选项
- 3 道题考 3 个不同的点，不要是同一件事的措辞变化
- 只有当图片本身是理解那道题的前提时，才在题干里用 markdown 嵌一张图：![这张图说明什么](图片链接)。不要为了好看加图',
    `remark` = '基于上面的内容出 3 道题（单选 / 多选 / 填空或简答）。素材可以是这条知识，也可以是用户粘的一段'
WHERE `user_id` = 0 AND `config_key` = 'ai.prompt.question.make_quiz:none';
-- ⚠️ **2026-10-22：这条引导问题（make_quiz）已经整套撤了**（旧自测题那套：
--    题存在库里 + 本地判分 + 每日复习）。上面那句 UPDATE 重放的话会把
--    `ai.prompt.question.make_quiz:none` 这条配置**又建回来** ——
--    撤表脚本是 2026-10-22_drop_old_quiz_feature.sql（它最后会把它删掉，
--    所以按日期顺序重放全部脚本的话，最终状态仍是对的）。


-- ----------------------------------------------------------------------------
-- 3/4  树：分类节点直接变成叶子「全局人设」，原来那层「问答统一描述」删掉
-- ----------------------------------------------------------------------------
-- 「场景统一描述」这个容器（config_key = ai.prompt.system，value_type 为空）
-- 变成叶子本身：名字改「全局人设」、value_type 改 text、说明改一句。
-- 它的父本来就是「AI 提示词」（parent_id = 4），code 也是 'system'，键不用动。
UPDATE `corecraft`.`sys_config_node`
SET `name` = '全局人设',
    `value_type` = 'text',
    `remark` = '所有任务共用的一段系统描述：你是谁、回答风格、不许编。任务规则在引导问题里'
WHERE `config_key` = 'ai.prompt.system' AND `value_type` IS NULL;

-- 原来挂在它下面的叶子（问答统一描述 / ai.prompt.system.chat）没用了
DELETE FROM `corecraft`.`sys_config_node` WHERE `config_key` = 'ai.prompt.system.chat';


-- ----------------------------------------------------------------------------
-- 4/4  核对
-- ----------------------------------------------------------------------------
-- 4.1 AI 提示词分支：应该是「全局人设」+「引导问题」两个分支，各带对的孩子
SELECT `id`, `parent_id`, `name`, `code`, `config_key`, `value_type`, `sort`
FROM `corecraft`.`sys_config_node`
WHERE `config_key` LIKE 'ai.prompt%'
ORDER BY `parent_id`, `sort`, `id`;

-- 4.2 提示词的值：7 条（1 条全局人设 + 6 条引导问题），user_id 都要是 0
SELECT `user_id`, `config_key`, CHAR_LENGTH(`config_value`) AS len, LEFT(`config_value`, 30) AS head
FROM `corecraft`.`sys_config`
WHERE `config_key` LIKE 'ai.prompt%'
ORDER BY `config_key`;

-- 4.3 确认没有残留的旧键
SELECT COUNT(*) AS leftover_old_key
FROM `corecraft`.`sys_config` WHERE `config_key` = 'ai.prompt.system.chat';
