-- 目标配置：sys_config / ai.prompt.knowledge.point（user_id = 0）
--
-- ## 为什么改
--
-- 用户实测生成的「安装 JDK」正文：前两段硬锁 `### 1. 定义` / `### 2. 原理`
-- 对**操作/流程类**知识点必然错位 ——「安装」没有"原理"，模型只能借
-- 「3. 特征与对比」（PATH/JAVA_HOME/CLASSPATH 三个变量的机制）和
-- 「4. 应用」（重开终端才生效）的料来填「原理」段，造成：
--   ① 段落间重复（PATH 在原理段讲一遍、对比表再讲一遍）
--   ② 目录与知识脱节（「2. 原理」其实是杂烩段，看不出跟"安装"的关系）
--   ③ 下一段被掏空去凑数（应用段扯 Docker/CI/IDE 这类任何主题都能套的通用场景）
--
-- 根因：这是**通用平台**（财务/地理/法律/历史/数学/语言…五花八门），
-- 把"概念类知识"的讲法（定义+原理）当成所有知识的默认，必然在非概念类上翻车。
--
-- 顺带收两条判据失效：
--   · 「常见考点」的「技术类默认写」让判据变成默认（实测命中率 91-96% 虚高）
--   · 段落池「挑 1 到 3 段」实际几乎都顶格挑满（多写一段不会被罚）
--   · 「应用」的「后端/云原生视角」是硬编码的领域偏向（同日领域偏向 4 处之一）
--
-- ## 改了什么（都在「正文分段」这一个块里）
--
-- ① 前两段**锁功能不锁字面**：
--    - 第 1 段 = "是什么"段（标题一般叫「定义」，制度/事件/工具可叫「是什么」「作用与目标」）
--    - 第 2 段 = "核心讲法"段，从「怎么成立/怎么运转/怎么操作/怎么证明/怎么演变/
--      由什么构成」里挑一个能讲透的角度；标题按内容类型起（原理/怎么操作/内部结构/
--      证明思路/背景与经过/构成要件），**清单是示范不是穷举**，清单外领域自己起
--    - 新增「前两段标题的硬规矩」：带序号名词短语 ≤12 字 / 关键词须能在段首句找到
--      依据 / 不许空壳 / **「原理」不是万能兜底**
-- ② 段落池「挑 1 到 3 段」→「**挑 1 到 2 段**」，补充说明「面向考试」时放宽到 3
-- ③ 「应用」判据：真实工程/使用场景 → **主题特有的、容易踩坑的场景**；
--    「任何主题都能扯上的通用场景不算」（打包/部署/IDE），**删「后端/云原生视角」**
-- ④ 「常见考点」判据：删「技术类默认写」→ **能写出 2 个具体的问法才写**
--
-- ⚠️ 一整块 REPLACE、带 LIKE 守卫：只改一次，不会出现半新半旧的中间版本。
-- ⚠️ 生效时机：sys_config 每次生成时读库 ⇒ 改完立即生效，但**生成中的任务不吃新 prompt**。
--
-- 实际执行：2026-11-09 通过 tmp/section-flex-apply.mjs 参数化 UPDATE（先校验
-- 库里现值与 _backup/ai.prompt.knowledge.point.2026-11-09-before-section-flex.txt
-- 逐字节一致 + 4 个旧标记齐全，再写，回读 5540 字符逐字节一致）。
-- 本文件留档：供无 MCP 环境重放。4971 → 5540 字符。
