UPDATE `corecraft`.`sys_config`
SET `config_value` = REPLACE(
  `config_value`,
  '  - **必写 ① `### 1. 定义`**：一句话说清定义、全称、所属领域，再补一句它的边界（跟什么不是一回事）
  - **必写 ② `### 2. 原理`**（机制 / 依据 / 展开）：它到底怎么成立的、关键步骤或判据；**列成要点清单**
  - **段落池（判据在先：不满足就不写这一段；从里面挑 1 到 3 段，按顺序接着编号）**：
    - `### 3. 特征与对比` —— **有至少一个相近概念、且区别是理解它的关键**时才写（**用表格对比**）
    - `### 4. 组成与结构` —— 它**由多个部件构成、或本身有层次**时才写（讲清每部分干什么）
    - `### 5. 应用` —— **有真实工程 / 使用场景**时才写（后端/云原生视角、注意事项）
    - `### 6. 演进与历史` —— 版本变迁或来龙去脉**本身就是理解它的重点**时才写
    - `### 7. 常见考点` —— 这个概念**会出现在考试 / 面试里**才写；它是出题的素材，**技术类默认写**（最常考的点、容易记错或答错的地方、可能的问法 + 一句话答案）',
  '  - **必写 ① `### 1. ...`**（"是什么"段）：一句话说清定义、全称、所属领域，再补一句它的边界（跟什么不是一回事）。标题一般用 `### 1. 定义`；内容是制度 / 事件 / 工具时，也可以用「是什么」「作用与目标」这类更贴的名字
  - **必写 ② `### 2. ...`**（"核心讲法"段）：从「它怎么成立、怎么运转、怎么操作、怎么证明、怎么演变、由什么构成」里挑**一个这个知识能讲透的角度**展开，**列成要点清单**。标题由角度决定，**不是固定叫"原理"**：
    - 概念 / 机制类 → `### 2. 原理`
    - 操作 / 配置 / 流程类 → `### 2. 怎么操作`（或「配置步骤」）
    - 结构 / 组成类 → `### 2. 内部结构`
    - 数学定理 / 公式 → `### 2. 证明思路`
    - 历史事件 / 制度变迁 → `### 2. 背景与经过`
    - 法律条文 → `### 2. 构成要件`
    - **上面都不沾的，自己起一个贴合的名字** —— 例子是示范，不是清单
  - **前两段标题的硬规矩**：① 带序号、名词短语、**≤ 12 字**；② 标题里的关键词必须能在本段第一句话里找到依据；③ 不许空壳（「相关说明」「几点补充」不行）；④ **「原理」不是万能兜底** —— 只有真的在讲因果机制时才准用
  - **段落池（判据在先：不满足就不写这一段；从里面挑 1 到 2 段，按顺序接着编号；补充说明写了「面向考试」时可以放宽到 3 段）**：
    - `### 3. 特征与对比` —— **有至少一个相近概念、且区别是理解它的关键**时才写（**用表格对比**）
    - `### 4. 组成与结构` —— 它**由多个部件构成、或本身有层次**时才写（讲清每部分干什么）
    - `### 5. 应用` —— **有这个主题特有的、容易踩坑的使用场景**时才写（注意事项、工程实践；**任何主题都能扯上的通用场景不算**，比如「打包 / 部署 / IDE 里也能用」）
    - `### 6. 演进与历史` —— 版本变迁或来龙去脉**本身就是理解它的重点**时才写
    - `### 7. 常见考点` —— 这个概念**真的会出现在考试 / 面试里**、且**能写出 2 个具体的问法**才写；写不出具体问法就不写（最常考的点、容易记错或答错的地方、可能的问法 + 一句话答案）'
)
WHERE `user_id` = 0
  AND `config_key` = 'ai.prompt.knowledge.point'
  AND `config_value` LIKE '%必写 ② `### 2. 原理`%';

