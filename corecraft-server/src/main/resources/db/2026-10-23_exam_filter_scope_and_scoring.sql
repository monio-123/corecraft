-- 出卷：题面取材规则 + 题量结构加「分值」
-- 2026-10-23
--
-- 背景（用户 2026-10-23 提的两条）：
--
--   ① **题面不要抛业务表名/字段名**。
--      实测出的题长这样：「要从 alert_cur_event 中按 rule_name、severity、target_ident
--      三列去重，并保留每组中 id 最大的那条完整记录。下列哪种做法符合这个目标？」
--      —— 表名、字段名、场景全是知识点里那套业务对象，读者一脸茫然：
--      **考的是知识点里的方法，不是它碰巧用到的那张表**。
--      ⇒ 规范里加一条：题干里要出现表、字段、类名时，用**最简单的通用例子**
--      （表 t，字段 id、name、status）；知识点里的代码/写法本身就是要考的东西，就直接引出来问。
--
--   ② **分值**：一个考卷出的时候把分定好，判分按每题的分值折算。
--      ⇒ `ai.prompt.exam.types` 的行格式从「题型|道数」扩成「**题型|道数|分值**」
--      （分值那一段可省 ⇒ 默认 1 分/题，老配置不写也照旧）。
--      默认阶梯取常见的：单选 1 / 多选 2 / 填空 2 / 概念 5 / 面试 10 ⇒ 3×3×3×3×3 = 60 分。
--      **分值是前端的账，判分只给三档判定**（对 / 部分对 / 错）：
--      对 = 满分，部分对 = 一半，错 = 0（规范里本来就只写了这三档，不用改判分规范）。
--
-- ③ 顺带把**出卷入口**从目录行挪回**列表页的筛选条**（范围 = 当前筛选出来的那些，
--    未归类的条目不参与 —— 待归类不是目录，用户 2026-10-23 定）。
--    ⇒ 这一条是**代码改动**（前端），不在本脚本里。
--
-- 执行时机：随时（出卷时读的就是这几条，不用发版）。


-- ========== 题量结构：加「分值」 ==========
UPDATE corecraft.sys_config
SET config_value = '单选|3|1
多选|3|2
填空|3|2
概念|3|5
面试|3|10'
WHERE user_id = 0
  AND config_key = 'ai.prompt.exam.types';


-- ========== 出卷规范：加「题面取材」那条 ==========
UPDATE corecraft.sys_config
SET config_value = '每道题的写法：
- 题头写成 ## 编号（题型），括号里写中文题型：单选 / 多选 / 填空 / 概念 / 面试
- 单选、多选：题干一行，然后 4 个选项各一行，前面是字母加一个点：A. 内容。单选 4 个选项、只有 1 个正确；多选 4 个选项、至少 2 个正确。选项写完，另起一行写「答案：」，后面只写正确选项的字母，单选写一个字母，多选把字母连着写（答案：B / 答案：AB）
- 填空：题干一行，然后写「答案：」，后面只写那个词或短语，不要写整句话
- 概念、面试：题干一行，然后写「参考答案：」，下面另起行写 3 到 5 条要点，每条前面加 "- "，每条不超过 40 字
- 答案单独一行，不和题干挤在一起

先定考点，再出题：
第一步，写一份考点清单（一行一个考点，不编号，不要用 ## 标题）：上面给的内容里的每一个点各占一行
第二步，照着清单逐题写，一个考点出一道题
- 清单里的考点个数最多和题量结构的总题数一样：材料撑不住就少出题，每种题型的道数也不要超过题量结构给它配的数量
- 题号按题量结构给的位置写：某一种题型少出时，保留它应占的题号（可以跳号），不要把后面的题号往前挪
- 一个考点只能考一次，换个说法再问一遍算重复
- 不同题型的考点也要错开：同一批知识点不要在单选里问一遍、多选里再问一遍
- 宁可多考几个相邻但不同的点，也不要把同一个概念反复问

考什么：
- 材料按类型分组，每组前面标着这一组的类型名：【笔记】是具体知识点，【学习】是这个领域的框架与体系
- 考的是知识点里的方法、结论、写法，不是它碰巧用到的那张业务表、那套字段名：题干里要出现表、字段、类名时，用最简单的通用例子（比如表 t，字段 id、name、status），不要拿知识点里的业务表名、字段名当题面抛给读者；知识点里的代码或写法本身就是要考的东西，就直接把它引出来问
- 出单选、多选、填空时，正确答案必须能在材料里找到明确依据，不能靠常识补：优先用【笔记】里的原文；材料里没有【笔记】、只有【学习】时，就用【学习】里写明的具体结论，只是罗列结构、没有具体结论的部分不当考点
- 出概念题、面试题时，优先用【学习】的框架叙述，讲清结构、边界、模块之间的关系；没有【学习】就用【笔记】的要点
- 材料里没写到的具体内容不要考：考的是这份材料本身，不是这个主题的全部
- 只考和上面这个主题直接相关的，不要扯到相邻话题
- 选择题的选项是不同的理解或做法，成立的那些才是正确项；不要把内容里并列写的几行拆开当选项
- 可以直接用这个主题常见的考法和经典表述，但说法可以换、事实不能换

选择题的构造规则：
- 正确项的位置要打散：按题号轮换着来（第 1 题 A、第 2 题 C、第 3 题 B、第 4 题 D，这样循环），不要一道接一道都落在同一个字母上；多选的正确项个数在 2 和 3 之间轮换，不要每道都是 ABC
- 错误项必须是「看着像对的」：同一个概念下常见的误解、把适用条件搞错、把边界说反、把相近的两个概念搞混——不许拿明显不相关的说法凑数
- 明确禁止「一眼排除」的干扰项：只读完题干、不懂这个知识也能排除掉某个选项，那道题就是废题
- 四个选项不许出现「只有一个最完整 / 最长 / 最具体」这种一望而知的破绽
- 题干里不要直接照抄正确项的说法：正确项换个说法写，别让人扫一眼题干就选出来
- 题干要有一个需要动脑的地方：给条件、给场景、给对比、给「在什么情况下」，让人必须回材料里找依据才能判断，而不是读一遍字面就能选

每道题必须能单独存在：读者手上只有这道题，看不到前面的内容。
- 把要考的概念本身写进题干，不要铺垫「某人正在做某事」这种引子
- 不许出现「上面提到的」「本文」「方法一」「笔记里」这类只有看过原文才懂的指代
- 题干里不要嵌图片

清单写完就接着写题目，不要复述内容，不要加开场白或小结。'
WHERE user_id = 0
  AND config_key = 'ai.prompt.exam.paper';


