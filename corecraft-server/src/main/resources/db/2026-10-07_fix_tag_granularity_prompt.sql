-- ============================================================
-- 修正标签提示词的粒度（2026-10-07）
--
-- ## 为什么要改
--
-- 库里的实情：36 个标签里**只有 2 个被复用**（sql 6 次、基本数据类型 2 次），
-- 23 个只用过一次，11 个一次没用上。一次性的标签分三类：
--
--   该粗不粗：MySQL / 数据库连接 / 连接数 / JDBC 各一次；MyBatis / 索引 / 复合索引 /
--             唯一约束 / 唯一字段 / order by / 排序 / 分页 各一次；财务 / 财务基础知识
--   根本不是标签：max_connections、Threads_connected、SHOW STATUS、allowPublicKeyRetrieval
--             （命令名和参数名，就是正文里的字）
--   压根没法当标签：JSON、字符串、对象转换（一整句话）
--
-- 三处病因，都在 remark 里：
--
--   1.「**3 到 5 个**」这个数量下限在逼模型填垃圾。真能复用的可能就 2 个，
--      模型为了凑够下限就拿正文里的词补齐——**数量下限 = 垃圾生产器**。
--   2.「核心概念（**方法名**、协议名、概念名）」里的"方法名"就是在邀请参数名和命令名。
--      `max_connections` 是参数、`SHOW STATUS` 是命令，按原来那句写它们完全合规。
--   3. 一次问全的 organize 那条有**同样的毛病**，不改的话批量归类带着同一个 bug 上线。
--   4. **没说清标签和目录的分工**，于是打出一个和目录重复的标签。这是最要命的一条——
--      知识已经归在「Java › 泛型」下面，标签再打一个「泛型」：两份真相，
--      而且目录一改标签不会跟着变（skill §2.2 那条「两份真相早晚会不同步」）。
--
-- ## 「标签 vs 目录」写进去之后，字数只剩 31 个字符的余量
--
-- varchar(255)。所以先压掉了「合适的：MySQL、索引、序列化」那行正例——
-- 正例由「目录叫 Java›泛型 就别再打泛型，标签只打目录管不到的（类型擦除、JVM 内存）」
-- 这一句顺带给了：类型擦除 / JVM 内存 本身就是好标签的样子。
--
-- ## ⚠️ 改的时候差点走错的一条路
--
-- 曾经打算在喂给模型的标签清单里带上 `refCount`，写"优先挑用量 >= 2 的"。
-- **那是拿指标优化答案**：这条知识该打什么标签，只取决于它**涉及**什么，
-- 跟别的知识用没用过这个标签毫无关系。照那个改，模型会因为 `sql` 用得多
-- 就给一条完全无关的知识也打上 `sql`。
--
-- 判据只有一条：**合适**。"空的就空"，凑数出来的标签是垃圾，比没有更糟。
--
-- 标签清单（`appendContext` 的 tags 分支）仍然要喂，但作用是**统一叫法**——
-- 别一条知识写 `Java` 另一条写 `JAVA`。它是词表，不是推荐列表。
-- ============================================================

-- pick_tags：详情页抽屉里那条引导问题
UPDATE `sys_dict_item` SET `remark` = '这条知识「涉及」哪些概念。判据：换个知识点它还成立吗？只在这条里成立的是正文，不是标签（max_connections、SHOW STATUS 这种命令名和参数名都不算）。
别和目录重复：目录管「属于哪个」，标签管「涉及什么」。一条知识只能待在一个目录里但能涉及多个概念——目录叫「Java›泛型」就别再打「泛型」，标签只打目录管不到的（类型擦除、JVM 内存）。
数量 0 到 4 个，宁缺毋滥。下面的清单只为统一叫法，符合就用，不符合别硬套。'
WHERE `dict_type_id` = (
  SELECT id FROM `sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `value` = 'pick_tags:tags' AND `is_delete` = 0;

-- organize：列表页「AI 归类」一次问全用的那条
UPDATE `sys_dict_item` SET `remark` = '这条知识还没起名字、没归类、没打标签。一次给全，严格按下面三段输出，除此之外不要写任何解释：
名字：<12 个字以内，说清它讲的是什么，不要用「详解」「介绍」这类空词>
目录：<从下面这份目录清单里挑最贴切的一个，原样输出清单里的名字；都不合适就写「都不合适，建议新建一个」>
标签：
- <这条知识「涉及」的概念，0 到 4 个。换个知识点它还成立吗？只在这条里成立的是正文不是标签。目录管「属于哪个」、标签管「涉及什么」，目录叫「Java›泛型」就别再打「泛型」。宁缺毋滥>'
WHERE `dict_type_id` = (
  SELECT id FROM `sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `value` = 'organize:categories,tags' AND `is_delete` = 0;
