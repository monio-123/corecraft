-- 知识点正文提示词：补上 mermaid 四种画法的示例与硬规矩
--
-- 日期：2026-11-12
-- 目标配置：sys_config / ai.prompt.knowledge.point（user_id = 0）
--
-- ## 为什么改
--
-- 提示词里「结构化图」那侧写得很细：四种形状各有一个完整示例 + 一段硬规矩
-- （`layers` / `stages` / `stages + 侧翼` / `pairs`）。而 **mermaid 那侧只有一句话**：
-- 「谁跟谁连着」「有哪几个状态、怎么流转」「多个角色按先后交互」「带判断分支的流程」
-- —— **一个示例都没有**，也没有任何格式约束。
--
-- 后果是模型画 mermaid 只能自由发挥：语法写错（图不出现）、节点堆到二十个（挤成一团）、
-- 写 `style` 盖掉主题配色、状态图只画往前的单链（把回退分支画丢）。
--
-- 2026-11-12 用户库里新写的 7 条「图能力」知识点（id 3029~3035）把这几类讲清楚了，
-- 其中 4 类就是 mermaid：调用依赖 / 状态流转 / 多方交互 / 判断分支。
-- 这些内容此前**不在提示词里** —— 模型写得出只是碰巧。
--
-- ## 示例里的每一条语法都实测过（mermaid 12.2.0 + 本项目渲染层）
--
-- - `graph LR` + `[(圆柱)]` + `[[双框]]` + `-.->`  → 通过
-- - `graph TD` + `{菱形}` + `-->|条件|`            → 通过
-- - `stateDiagram-v2` + 中文状态名 + 回边          → 通过
-- - `sequenceDiagram` + `participant X as 中文`    → 通过
-- - `A[库存(扣减)]` **不加双引号 → 解析失败**（这条必须写进提示词）
-- - `style A fill:#f00` → **能解析但会盖掉主题配色**，所以要禁
--
-- ## 回滚
--
-- 两段各自反向 REPLACE，见文件末尾。
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 【跑前校验】改前总长应在 6,143 上下；「mermaid 四种画法」应为 0
-- ---------------------------------------------------------------------------
SELECT
  CHAR_LENGTH(MAX(config_value))                        AS 改前总长,
  SUM(config_value LIKE '%mermaid 有四种画法%')          AS 新段已存在,
  SUM(config_value LIKE '%- **mermaid**（写成%')         AS 原mermaid句
FROM `corecraft`.`sys_config`
WHERE `user_id` = 0 AND `config_key` = 'ai.prompt.knowledge.point';


-- ---------------------------------------------------------------------------
-- 【第 1 段】mermaid 那句：用途清单对齐四种画法（原来列了 5 条、和下面的例子对不上）
-- ---------------------------------------------------------------------------
UPDATE `corecraft`.`sys_config`
SET `config_value` = REPLACE(
  `config_value`,
  '  - **mermaid**（写成 ```mermaid 代码块）：「谁跟谁连着（调用 / 依赖）」「有哪几个状态、怎么流转」「多个角色按先后交互」「版本演进 / 历史变迁」「**带判断分支的流程**」。需要自动布局的都用它。',
  '  - **mermaid**（写成 ```mermaid 代码块）：「**谁依赖谁**（调用 / 依赖）」「**按什么条件分支**」「**有哪几个状态、怎么流转**」「**谁按什么顺序和谁说话**」「版本演进 / 历史变迁（这一种用 `timeline`，一行一个「时间 : 事件」）」。需要自动布局的都用它 —— 四种画法的例子见下面。'
)
WHERE `user_id` = 0
  AND `config_key` = 'ai.prompt.knowledge.point'
  AND `config_value` LIKE '%- **mermaid**（写成%';


-- ---------------------------------------------------------------------------
-- 【第 2 段】在「图的硬规矩」之前，插入 mermaid 四种画法 + 例子 + 硬规矩
--
-- ⚠️ 例子比描述重要：2026-11-09 回测过，模型模仿示例的能力远强于理解文字。
-- ⚠️ 硬规矩里的第 ② 条是实测踩出来的：标签里出现 `(` 时不加双引号会**直接解析失败**，
--    症状是「图没画出来」，而模型看不出自己错在哪。
-- ---------------------------------------------------------------------------
UPDATE `corecraft`.`sys_config`
SET `config_value` = REPLACE(
  `config_value`,
  '- **图的硬规矩**：①一个知识点最多一张图',
  '- **mermaid 有四种画法**（语法照抄例子，括号形状和箭头样式都别改）：\n  - `graph LR` —— **谁依赖谁**（调用 / 依赖）：方框是服务，`[(圆柱)]` 是存储，`[[双框]]` 是消息队列；`-->` 同步、`-.->` 异步：\n```mermaid\ngraph LR\n  C[客户端] --> G[网关]\n  G --> O[订单服务]\n  O --> P[商品服务]\n  O --> MQ[[订单事件 MQ]]\n  MQ -.-> N[通知服务]\n  P --> DB[(商品库)]\n```\n  - `graph TD` + 菱形 —— **按什么条件走**：判断写成 `{...}`（菱形），出边写 `-->|条件|`，互斥的两条都要画出来：\n```mermaid\ngraph TD\n  A[请求] --> B{缓存命中}\n  B -->|命中| C[直接返回]\n  B -->|未命中| D{查库结果为空}\n  D -->|是| E[布隆过滤器拦掉]\n  D -->|否| F[回源并回填]\n```\n  - `stateDiagram-v2` —— **有哪几个状态、怎么流转**：**状态写成名词**（「已支付」不是「支付」）；**回退的边一定要画出来**（退款被驳回后回到已发货），只画往前的单链等于把最关键的分支画丢；`[*]` 是起点和终点：\n```mermaid\nstateDiagram-v2\n  [*] --> 待支付\n  待支付 --> 已支付: 支付成功\n  已发货 --> 退款中: 申请退款\n  退款中 --> 已发货: 驳回退款\n  退款中 --> 已退款: 退款完成\n  已支付 --> [*]\n```\n  - `sequenceDiagram` —— **谁按什么顺序和谁说话**：参与方先用 `participant X as 中文名` 声明；重点是**每一步是谁发给谁的**（不是「有几步」）：\n```mermaid\nsequenceDiagram\n  participant U as 用户\n  participant A as 客户端应用\n  participant S as 授权服务器\n  U->>A: 点击登录\n  A->>S: 跳转 authorize 带 client_id\n  S->>A: 回调带 code\n  A->>S: 用 code 换 token\n```\n- **mermaid 的硬规矩**：①节点 / 参与方 **≤ 10 个、每个标签 ≤ 14 字**（再多就挤成一团，长说明放到正文里）；②**标签里出现括号 `()` `[]` `{}`、冒号或引号时，整个标签用双引号包起来**（`A["库存(扣减)"]`）—— 不包会**语法错、整张图出不来**（实测）；③**不许写 `style` / `classDef` / `linkStyle` / 颜色 / 字号**（配色由渲染层按主题给，写死了切主题就花）；④状态图**至少要有一条回边或终态**，全是往前走的就改用结构化图的 `stages`；⑤`graph` 里**没有菱形判断就不叫分支**，纯顺序也用 `stages`；⑥**一张图只讲一件事**（调用链和状态机不要画在同一张里）\n- **图的硬规矩**：①一个知识点最多一张图'
)
WHERE `user_id` = 0
  AND `config_key` = 'ai.prompt.knowledge.point'
  AND `config_value` LIKE '%- **图的硬规矩**：①一个知识点最多一张图%';


-- ---------------------------------------------------------------------------
-- 【跑后校验】五项都应命中；总长从 ~6,143 涨到 ~7,700
-- ---------------------------------------------------------------------------
SELECT
  CHAR_LENGTH(MAX(config_value))                              AS 改后总长,
  SUM(config_value LIKE '%mermaid 有四种画法%')                AS 四种画法,
  SUM(config_value LIKE '%[[订单事件 MQ]]%')                   AS 关系图例子,
  SUM(config_value LIKE '%退款中 --> 已发货: 驳回退款%')        AS 状态回边例子,
  SUM(config_value LIKE '%participant S as 授权服务器%')        AS 时序图例子,
  SUM(config_value LIKE '%mermaid 的硬规矩%')                   AS 硬规矩,
  SUM(config_value LIKE '%标签里出现括号%')                     AS 引号规矩,
  SUM(config_value LIKE '%`-.->` 异步%')                        AS 异步箭头
FROM `corecraft`.`sys_config`
WHERE `user_id` = 0 AND `config_key` = 'ai.prompt.knowledge.point';


