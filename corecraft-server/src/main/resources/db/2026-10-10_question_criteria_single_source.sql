-- 引导问题判据单一来源（2026-10-10）
--
-- ## 要解决什么
--
-- 目录判据、标签判据、命名判据原来在 `pick_*` 和 `organize` 里**各抄了一份**，
-- 调一次判据要同时 UPDATE 三条。漏过，而且**库里此刻就已经不同步**——
-- 2026-10-10 逐字比对库内现值，organize 相对两条单条引导问题少了：
--
--   · pick_category 的三个正例
--     （「MyBatis 一对多映射的分页」/「MySQL 连接数怎么看」/ 成套知识体系的概念）
--   · 「下面的清单只是『你已经用过哪些叫法』，用来统一叫法，它不是推荐清单」
--     —— drop_tech_stack_enumeration.sql 当天加的，只改了 pick_tags，没改 organize
--   · 「凑出来的标签是垃圾，比没有还糟」
--
-- 后果不是报错，是**批量归类拿到的判据比单条问答弱一档**，界面上完全看不出来。
--
-- ## 判据被删这件事，早就预言过
--
-- 2026-10-07_three_way_boundary.sql 第 35-38 行原话：
--
--   「organize 只剩 21 字符余量 …… 得先把『格式说明』和『判据』拆开（判据做成
--     独立编辑的字典项，后端按 contexts 拼进去），不然下一次就得删判据了。」
--
-- 「下一次」就是 10-07 当天。organize 的判据段被压缩到 488 字符，压缩掉的正是上面那几条。
-- 本脚本就是去执行这条预言。
--
-- ## 怎么改：remark 拆成三个行首标记
--
--   【引用】<字典项 value>   引用另一条的**判据段**（格式段不取）
--   【判据】…                判断标准，只该存在一份
--   【格式】…                输出格式要求
--
-- organize 改成引用 rename / pick_category / pick_tags 三条的判据，只留自己的三段输出格式。
-- 改判据从此只有一个归属，引用方自动跟随。
--
-- ## 判据和格式为什么必须分开
--
-- 单条问答要「原样输出目录名」，批量要「名字：/目录：/标签：三段键值行」。
-- 这两句硬凑进同一条里会**直接打架**——rename 判据里的「只输出名字本身」
-- 和 organize 的「按三段输出」互斥。所以格式必须留在引用方自己身上。
--
-- ## 提示词仍然全在字典里
--
-- 后端 `AiChatServiceImpl` 只加了「怎么读这三个标记」，**没有搬进来任何提示词正文**。
-- 这次改的是**读法**，不是**内容**：仍然在「字典 → AI-知识点默认问题」的备注框里编辑。
--
-- ## 兼容性
--
-- · remark 里没有标记的**整段原样用**——`make_quiz` / `comb` 完全不受影响。
-- · 【引用】断了（字典项被删/改名）**直接抛错、不静默跳过**：静默降级的症状是
--   「AI 少了条约束但看起来完全正常」，正是这次要根除的那类问题。
-- · 段内的空行会被丢掉。最终拼出来是一块平铺的指令文本，段内空行不承载信息。
--
-- ## 执行顺序（反了会静默失效）
--
-- ⚠️ **先发版后端（Java 改了），再执行本脚本。**
--    反过来的话，organize 那几行【引用】会被当成普通文本原样发给模型
--    ——批量归类看起来"能跑"，但**一条判据都不带**，比改之前更糟且毫无报错。
--
-- ## 关于库名
--
-- 同目录老脚本写的是不带库名的 `sys_dict_item`（当时客户端默认库就是 corecraft）。
-- 这里显式带 `corecraft`，免得在别的会话里跑、一条 UPDATE 打到 `sys` 库去还照样成功。
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1/4  命名判据 —— 拆成【判据】+【格式】两段，判据原文一字未改
-- ----------------------------------------------------------------------------
UPDATE `corecraft`.`sys_dict_item` SET `remark` = '【判据】这条知识还没起名字。读一遍正文，给它起一个：12 个字以内，直接说清它讲的是什么，不要用「详解」「介绍」「学习笔记」这类空词。
【格式】只输出名字本身，不要任何解释、引号或标点。'
WHERE `dict_type_id` = (
  SELECT id FROM `corecraft`.`sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `value` = 'rename:none' AND `is_delete` = 0;


-- ----------------------------------------------------------------------------
-- 2/4  目录判据 —— 拆分位置在「…挂「数据库」下面的新目录写「数据库/MySQL」。」之后
--      （判据到这结束；「只输出路径本身…这一栏只填名字」是格式，不进判据）
-- ----------------------------------------------------------------------------
UPDATE `corecraft`.`sys_dict_item` SET `remark` = '【判据】这条知识该归到哪个目录。
判断标准：这条知识主要在学谁，就归谁。
- 「MyBatis 一对多映射的分页」主要在讲 MyBatis → 目录 MyBatis；顺带涉及的 MySQL 写进标签
- 「MySQL 连接数怎么看」主要在讲 MySQL → 目录 MySQL
- 成套知识体系的概念（泛型、序列化）通常就是主归属
清单里有合适的就选最贴近的那一层，有更具体的别选更宽的。
要新建就用斜杠写出它该挂在哪下面：挂「数据库」下面的新目录写「数据库/MySQL」。
【格式】只输出路径本身。不要写理由、不要加括号、不要提「建议迁到某个目录」——目录和标签各管各的，这一栏只填名字。'
WHERE `dict_type_id` = (
  SELECT id FROM `corecraft`.`sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `value` = 'pick_category:categories' AND `is_delete` = 0;


-- ----------------------------------------------------------------------------
-- 3/4  标签判据 —— 同上，判据到「…它不是推荐清单。」为止
-- ----------------------------------------------------------------------------
UPDATE `corecraft`.`sys_dict_item` SET `remark` = '【判据】这条知识涉及哪些概念——主归属之外的那些。
主归属已经在目录里了，标签装的是剩下的。目录只能选一个，所以一条知识同时涉及好几个有体系的东西时，题目主要在讲哪个归哪个目录，其余的——哪怕它本身也是个正经的技术栈（一条讲 MyBatis 的笔记顺带说了 MySQL 的分页，MySQL 就写在这儿）——都放到标签里。
不是标签的是正文：具体的参数值（max_connections）、命令（SHOW STATUS）、一整句话（「JSON、字符串、对象转换」——那是一条知识的标题，不是标签）。
粒度要说清是哪种：「排序」太笼统，分不清是数据库里排、Java 对象里排还是 List 里排。
数量 0 到 4 个，宁缺毋滥。凑出来的标签是垃圾，比没有还糟。
下面的清单只是「你已经用过哪些叫法」，用来统一叫法，它不是推荐清单。
【格式】每行只写标签名本身，不要写理由、不要加括号。'
WHERE `dict_type_id` = (
  SELECT id FROM `corecraft`.`sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `value` = 'pick_tags:tags' AND `is_delete` = 0;


-- ----------------------------------------------------------------------------
-- 4/4  organize —— 判据整段删掉，改成引用上面三条
--
--      **这一条同时修掉了当前的 drift**：organize 从此跟着那三条走，
--      丢掉的三个正例、「清单不是推荐清单」、「凑出来的标签是垃圾」全部自动回来。
--
--      长度：488 → 约 180 字符。腾出来的余量是实打实的（varchar(1000)）。
-- ----------------------------------------------------------------------------
UPDATE `corecraft`.`sys_dict_item` SET `remark` = '【引用】rename:none
【引用】pick_category:categories
【引用】pick_tags:tags
【格式】这次一次给全，严格按下面三段输出，不要写别的解释，也不要写理由、加括号或引号。三段的值分别按上面引用到的规则来：
名字：
目录：
标签：
- <每行一个标签名>'
WHERE `dict_type_id` = (
  SELECT id FROM `corecraft`.`sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `value` = 'organize:categories,tags' AND `is_delete` = 0;


-- ----------------------------------------------------------------------------
-- 5/5  核对：organize 必须缩到 ~180 且以【引用】开头；另三条以【判据】开头
-- ----------------------------------------------------------------------------
SELECT `value`, CHAR_LENGTH(`remark`) AS len, LEFT(`remark`, 6) AS head
FROM `corecraft`.`sys_dict_item`
WHERE `dict_type_id` = (
  SELECT id FROM `corecraft`.`sys_dict_type` WHERE `code` = 'ai_topic_question' AND `is_delete` = 0
) AND `is_delete` = 0
ORDER BY `sort`;


