-- ============================================================================
-- 知识点类型（type）：与「目录 / 标签」并列的第四个正交维度
--
-- 2026-10-06
--
-- 为什么要有：日常记的是**场景笔记**（遇到问题当场记），但偶尔要**系统地学一块**
-- （比如把「计算机网络 / HTTP」从头梳理一遍）。这两类东西在 kp_topic 里长得
-- 一模一样——同一种实体、同样的目录和标签，混在一个列表里，筛不出"成体系的那部分"。
--
-- 三个维度的分工：
--   目录 category —— 这条知识**属于**哪      （单选，树的骨架）
--   标签 tag     —— 这条知识**涉及**什么    （多选，跨目录检索）
--   类型 type    —— 这条知识**是什么性质**  （单选，区分随手记 / 系统学）
-- 与目录、标签都不互相混，也不参与建树。
--
-- ⚠️ 类型**存字典**（sys_dict_item），不给它建独立主表。理由：
--   ① 字典是全局的，所以**每个用户天然都有默认档**。每用户自建的表做不到这点——
--      新建的用户打开就是"一个类型都没有"。
--   ② 增删改走现成的「资源管理 → 字典管理」，不用另做一套业务界面。
--   ③ kp_topic.type_id 存 **sys_dict_item.id（纯数字）**，代码里不写"1 = 笔记"
--      任何一个字，字典项增删排序都不影响任何代码——数字解耦。
--
-- 「默认档」不靠标记列，靠**排第一的那条**（sort 最小）：新建知识点时默认选它，
-- 它改名也还是默认。「笔记」只是我们预置的第一条，不是什么特殊身份。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. kp_topic 加引用列，指向 sys_dict_item.id
--    没有外键约束：字典项是软删的（is_delete），加外键反而会在字典管理里
--    删项时被卡住。查不到对应字典项时前端兜底成"排第一的那档"。
-- ---------------------------------------------------------------------------
ALTER TABLE kp_topic
    ADD COLUMN `type_id` bigint DEFAULT NULL COMMENT '知识点类型（指向 sys_dict_item.id；查不到时兜底为排第一的那档）' AFTER `content`,
    ADD KEY `idx_type_id` (`type_id`);

-- ---------------------------------------------------------------------------
-- 2. 建字典类型
-- ---------------------------------------------------------------------------
INSERT INTO sys_dict_type (code, name, remark, is_enabled)
VALUES ('kp_topic_type', '知识点类型', '随手记 / 系统学习…… 决定列表页能按什么筛选', 1);

-- ---------------------------------------------------------------------------
-- 3. 预置第一条 = 默认档「笔记」
--    value 存 'note' 只是字典内的唯一标识（uk 是 (dict_type_id, value)），
--    kp_topic 引用的是 id=2，不引用 value。
-- ---------------------------------------------------------------------------
INSERT INTO sys_dict_item (dict_type_id, label, value, sort, remark, is_enabled)
VALUES (LAST_INSERT_ID(), '笔记', 'note', 1, '默认档。排第一的那条就是新建知识点时的默认值', 1);

-- ---------------------------------------------------------------------------
-- 4. 已有知识点全部指到「笔记」
--    字典项 id = 2（本次执行值；换库执行要重新查 LAST_INSERT_ID()，别照抄）
-- ---------------------------------------------------------------------------
UPDATE kp_topic SET type_id = 2 WHERE type_id IS NULL;

-- ---------------------------------------------------------------------------
-- 回查
-- ---------------------------------------------------------------------------
SELECT t.id AS dict_type_id, t.code, t.name, i.id AS item_id, i.label, i.value, i.sort
FROM sys_dict_type t LEFT JOIN sys_dict_item i ON i.dict_type_id = t.id AND i.is_delete = 0
WHERE t.code = 'kp_topic_type';

SELECT is_delete, type_id, COUNT(*) AS 条数 FROM kp_topic GROUP BY is_delete, type_id;

