-- ------------------------------------------------------------
-- 3. 新增一条提示词：给一条写好的知识点**单独挑标签**
--
-- ## 为什么要有这条（实测踩出来的）
--
-- 复用 `ai.prompt.question.pick_tags:tags` 直接调，模型**一个字都不吐**：
-- 它的推理原话是「没有合适的标签就返回空」——
-- 因为 pick_tags 的【格式】是「每行只写标签名本身」，
-- **没给"一个都没有"留出路** ⇒ 模型认为只能"什么都不写"⇒
-- 前端收到空串，**分不清是"没有标签"还是"调用失败"**。
--
-- ⇒ 这里另开一条，**判据【引用】现成那条（只有一份判据）**，
-- 只把【格式】补成「没有合适的标签就写一行「无」」。
-- 后端 `composeInstruction` 的【引用】只取引用那条的**判据段**（格式段不取），
-- 引用断了会抛错、不会静默降级。
--
-- ## 为什么键名带 `:tags`
--
-- `promptKeyOf` 按**有没有点**区分完整键/短名；`contextsOf` 按**第一个冒号**取附料。
-- `ai.prompt.knowledge.tags:tags` ⇒ 完整键 ⇒ 后端顺带把
-- **用户现有的标签名**附上（统一叫法就靠它）。
-- ------------------------------------------------------------

-- 3.1 配置树：知识体系下面加一条「挑标签」
INSERT INTO `corecraft`.`sys_config_node`
  (`parent_id`, `name`, `code`, `config_key`, `value_type`, `sort`, `remark`)
SELECT
  p.id,
  '挑标签',
  'tags',
  'ai.prompt.knowledge.tags:tags',
  'text',
  3,
  '给一条写好的知识点挑标签。判据与「选标签」共用一份，这里只补输出格式'
FROM `corecraft`.`sys_config_node` p
WHERE p.config_key = 'ai.prompt.knowledge'
  AND NOT EXISTS (
    SELECT 1 FROM (SELECT id FROM `corecraft`.`sys_config_node` WHERE config_key = 'ai.prompt.knowledge.tags:tags') x
  );

-- 3.2 提示词正文（系统默认，user_id = 0）
INSERT INTO `corecraft`.`sys_config`
  (`user_id`, `config_key`, `config_value`, `remark`)
SELECT
  0,
  'ai.prompt.knowledge.tags:tags',
  '【引用】pick_tags:tags\n【格式】每行只写标签名本身，不要写理由、不要加括号。\n**没有合适的标签就写一行「无」**，不要空着什么都不写。',
  '给一条写好的知识点挑标签时整份发给模型。判据与「选标签」共用一份，这里只补输出格式'
WHERE NOT EXISTS (
  SELECT 1 FROM (SELECT id FROM `corecraft`.`sys_config` WHERE user_id = 0 AND config_key = 'ai.prompt.knowledge.tags:tags') x
);


