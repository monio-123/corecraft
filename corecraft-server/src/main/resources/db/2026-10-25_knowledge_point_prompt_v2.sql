-- ============================================================
-- 2026-10-25 知识点正文提示词 v2：两段必写 + 三段按需、术语要解释、不硬凑
--
-- ## 为什么改
--
-- 起因：知识点「范式与反范式」的 2NF 那条里，「非主属性」「候选键」「部分函数依赖」
-- 全都用了，**一个没解释** —— 读者读到那里得自己去查这些词。
--
-- 查下来是**三条原因叠加**，不是模型不听话：
--
-- ① **提示词自相矛盾**。同一份提示词里同时写着：
--      「**五段都要写**，写不出来就写你确实知道的那部分，不要留空」
--      「正文是 markdown，**500 到 700 字**（一条知识点的总长，别超）」
--    「五段 + 表格 + 要举例」根本装不进 700 字 ⇒ 模型只能选一个，
--    实际全选了「五段都要写」：**161 条平均 1525 字，135 条超 700**。
--    ⇒ 「不要硬凑」这条**压根没写进提示词**，只藏在半句里，被「五段都要写」压着。
-- ② **软规范不生效**。提示词早就有「能举例就举例」，而「范式与反范式」那一条
--    生成时**一个例子都没有**（同目录另外三条的「原理」段只有 367–536 字，
--    它 1742 字）⇒ 「能/尽量」这种措辞在密度高的段上会被跳过。
-- ③ **五段模板不适配所有知识体系**。法律条文、哲学概念、纯历史事件
--    本来就没有「特征与对比」「常见考点」⇒ 硬填就是没活硬整。
--
-- ## 改成什么样
--
-- - **两段必写**（定义 + 原理）：这两段缺了，这条知识立不住。
-- - **三段按需**（特征与对比 / 应用 / 常见考点）：**不适用就整段跳过，不要硬凑**。
--   ⇒ 适配得了法律哲学类体系，又保住了「常见考点」这段（**出题的直接素材**）。
-- - **硬规矩三条**（比篇幅重要，不许省）：
--   ① 术语要解释：加粗的专业术语第一次出现时紧跟一句话说清它指什么
--      （判据可判定：正文本来就大量加粗，161 条里 98 条有）
--   ② 例子要具体：讲机制/规则/限制时紧跟一个具体例子
--   ③ 补充说明另起一段：不要写成上一行的缩进续行
--      —— **缩进续行在 markdown 里是同一段**，渲染出来跟上一句挤在一行
--      （「范式与反范式」那一条 6 个「例：」全是这么写的，就是它挤在一起的原因）
-- - **篇幅改成上限 + 取舍顺序**：至少 200 字（= 解析器 MIN_CONTENT，低于这个不落库），
--   **宁可短，不要凑**；超长没关系。
--
-- ## 为什么用 REPLACE 而不是整份覆盖
--
-- 整份覆盖的话，回滚段就得把旧文**逐字抄一遍**（1700 多字）——抄错一个字，
-- 回滚就回不到原样。改成**段级替换**：正向 old → new，回滚 new → old，
-- 两边都是同一对片段，抄写风险只有一份，而且**回滚是可验证的**
-- （跑完 SELECT 一看就知道换没换上）。
--
-- ⚠️ **每条 UPDATE 都带 LIKE 守卫**：片段对不上时**一条都不改**（affected=0），
-- 不会把提示词改成半新半旧的样子。
--
