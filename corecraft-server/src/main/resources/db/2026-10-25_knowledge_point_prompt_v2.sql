-- 1.1 篇幅那条：去掉做不到的「500 到 700 字」，换成下限 + 取舍顺序
UPDATE `sys_config`
SET `config_value` = REPLACE(
      `config_value`,
      '- **正文是 markdown，500 到 700 字**（一条知识点的总长，别超）',
      '- **正文是 markdown**（篇幅不设上限，但**至少 200 字** —— 低于这个数系统不落库）'
    )
WHERE `user_id` = 0
  AND `config_key` = 'ai.prompt.knowledge.point'
  AND `config_value` LIKE '%- **正文是 markdown，500 到 700 字**%';

-- 1.2 五段 → 两段必写 + 三段按需 + 硬规矩
UPDATE `sys_config`
SET `config_value` = REPLACE(
      `config_value`,
      '- **正文按五段写，小标题带序号、名字要规范**（像书里的目录）：
  1. `### 1. 定义`：一句话说清定义、全称、所属领域
  2. `### 2. 原理`：机制、流程、关键步骤；**列成要点清单**
  3. `### 3. 特征与对比`：它自己的特点；和相近概念的区别（**用表格对比**）
  4. `### 4. 应用`：真实工程里怎么用、典型场景、注意事项（后端/云原生视角）
  5. `### 5. 常见考点`：这个知识点最常被考的点、容易记错或答错的地方，以及可能的问法 + 一句话答案
  **五段都要写**，写不出来就写你确实知道的那部分，不要留空',
      '- **正文分段：两段必写，三段按需**（小标题带序号、名字要规范，像书里的目录）：
  - **必写 ① `### 1. 定义`**：一句话说清定义、全称、所属领域，再补一句它的边界（跟什么不是一回事）
  - **必写 ② `### 2. 原理`**（机制 / 依据 / 展开）：它到底怎么成立的、关键步骤或判据；**列成要点清单**
  - **按需 ③ `### 3. 特征与对比`**：它自己的特点；和相近概念的区别（**用表格对比**）
  - **按需 ④ `### 4. 应用`**：真实工程里怎么用、典型场景、注意事项（后端/云原生视角）
  - **按需 ⑤ `### 5. 常见考点`**：这个知识点最常被考的点、容易记错或答错的地方，以及可能的问法 + 一句话答案
  - **按需的那三段，不适用的就整段跳过，不要硬凑**（法律条文、哲学概念、纯历史事件本来就没有「特征与对比」）。**跳过的段不占号**：写了哪几段就按顺序编 1、2、3…
- **硬规矩（这几条比篇幅重要，不许省）**：
  - **术语要解释**：正文里**加粗的专业术语**，第一次出现时紧跟一句话说清它指什么（例：`**非主属性** = 不属于任何候选键的属性`）。
  - **例子要具体**：讲机制、规则、限制时，紧跟一个具体例子（表结构、代码片段、真实场景），不要只说「比如」就带过。
  - **补充说明另起一段**：例子、补充、例外**另起一段**（中间空一行），不要写成上一行的缩进续行 —— 缩进续行在 markdown 里是同一段，渲染出来会跟上一句挤在一行。
  - **宁可短，不要凑**：内容少就写少，**不要用套话、排比、把常识摊开成段落来充数**；写不满就写不满。
  - **超长没关系**：写多少由内容决定 —— 不要为了「看着丰满」加东西，也不要为了压字数删掉解释和例子。'
    )
WHERE `user_id` = 0
  AND `config_key` = 'ai.prompt.knowledge.point'
  AND `config_value` LIKE '%**正文按五段写，小标题带序号、名字要规范**%';

