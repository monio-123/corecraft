-- 出卷规范加「选择题的构造规则」+ 默认难度档从「基础」换成「进阶」
-- 2026-10-22
--
-- 为什么改（用户实测："单选题 8 成都是选 A、多选题 9 成都是 ABC、
-- 题目浅到光看答案就能看出来"）：
--   根因**全在提示词/配置**，代码一行都不用动：
--   ① 原规范只规定了「什么是正确项」，**完全没规定什么是错误项**
--      ⇒ 模型随手编三个一眼就能排除的干扰项；
--   ② **完全没约束正确项的位置**
--      ⇒ LLM 生成选项的自然写法就是「先想出正确项 → 写成 A → 再编三个干扰项」
--      ⇒ 单选永远选 A；多选永远 AB/ABC；
--   ③ 默认难度档是「基础」（`ai.prompt.exam.level` 的**第一行 = 默认档**，
--      见前端 `exam.js` 的 `parseLevels`），而基础档的定义就是
--      「答案在内容里写得清清楚楚」⇒ 浅是**默认值**造成的。
--
-- 怎么改：
--   ① `ai.prompt.exam.paper` 加一段「选择题的构造规则」：
--      正确项按题号轮换 / 错误项必须「看着像对的」/ 禁止「一眼排除」的干扰项 /
--      禁止「只有一个最完整」这种一望而知的破绽 / 题干必须有一个需要动脑的地方 /
--      题干不直接照抄正确项的说法。
--   ② `ai.prompt.exam.level` 把「进阶」挪到第一行（= 默认档），并加强进阶档描述。
--
-- 执行时机：随时（改完不用发版，出卷时读的就是这两条）。


-- ========== ① 出卷规范 ==========
UPDATE corecraft.sys_config
SET config_value = '每道题的写法：
- 题头写成 ## 编号（题型），括号里写中文题型：单选 / 多选 / 填空 / 概念 / 面试
- 单选、多选：题干一行，然后 4 个选项各一行，前面是字母加一个点：A. 内容。单选 4 个选项、只有 1 个正确；多选 4 个选项、至少 2 个正确
- 填空：题干一行，然后写「答案：」，后面只写那个词或短语，不要写整句话
- 概念、面试：题干一行，然后写「参考答案：」，下面另起行写 3 到 5 条要点，每条前面加 "- "，每条不超过 40 字
- 答案单独一行，不和题干挤在一起

先定考点，再出题：
第一步，写一份考点清单（一行一个考点，不编号，不要用 ## 标题）：上面给的内容里的每一个点各占一行，这个主题里常见、该掌握但内容里没写的概念各占一行
第二步，照着清单逐题写，一个考点出一道题
- 清单里的考点个数要和题量结构的总题数一样
- 一个考点只能考一次，换个说法再问一遍算重复
- 不同题型的考点也要错开：同一批知识点不要在单选里问一遍、多选里再问一遍
- 宁可多考几个相邻但不同的点，也不要把同一个概念反复问

考什么：
- 上面给的内容是基础和重点，不是边界：内容里写了的一定要考到；内容里没写、但这个主题本来就该掌握的，也要考
- 只考和上面这个主题直接相关的，不要扯到相邻话题
- 选择题的选项是不同的理解或做法，成立的那些才是正确项；不要把内容里并列写的几行拆开当选项
- 可以直接用这个主题常见的考法和经典表述，不必拘泥于内容里的原话

选择题的构造规则：
- 正确项的位置要打散：按题号轮换着来（第 1 题 A、第 2 题 C、第 3 题 B、第 4 题 D，这样循环），不要一道接一道都落在同一个字母上；多选的正确项个数在 2 和 3 之间轮换，不要每道都是 ABC
- 错误项必须是「看着像对的」：同一个概念下常见的误解、把适用条件搞错、把边界说反、把相近的两个概念搞混——不许拿明显不相关的说法凑数
- 明确禁止「一眼排除」的干扰项：只读完题干、不懂这个知识也能排除掉某个选项，那道题就是废题
- 四个选项不许出现「只有一个最完整 / 最长 / 最具体」这种一望而知的破绽
- 题干里不要直接照抄正确项的说法：正确项换个说法写，别让人扫一眼题干就选出来
- 题干要有一个需要动脑的地方：给条件、给场景、给对比、给「在什么情况下」，让人必须回材料里找依据才能判断，而不是读一遍字面就能选

每道题必须能单独存在：读者手上只有这道题，看不到前面的内容。
- 把要考的概念本身写进题干，不要铺垫「某人正在做某事」这种引子
- 不许出现「上面提到的」「本文」「方法一」「笔记里」这类只有看过原文才懂的指代
- 题干里不要嵌图片

清单写完就接着写题目，不要复述内容，不要加开场白或小结。'
WHERE user_id = 0
  AND config_key = 'ai.prompt.exam.paper';


-- ========== ② 难度档位（第一行 = 默认档） ==========
UPDATE corecraft.sys_config
SET config_value = '进阶|考对比、边界条件和实际应用，需要推理才能答；不能只考定义，答案不能从题干字面直接推出
基础|只考定义和直接结论，考的是材料里写明的东西'
WHERE user_id = 0
  AND config_key = 'ai.prompt.exam.level';


