-- ============================================================
-- AI 提议新目录时能指定挂在哪个现有目录下面（2026-10-07）
--
-- ## 起因
--
-- 第五次实机：3 条知识全被建到了**顶层**，而 `MySQL` / `JDBC` 显然该挂在
-- 「数据库」下面——和「持久化」「Mybatis」「Lombok」平级。用户原话：
-- 「这个目录是建在顶层的 感觉不对吧 至少该归属于数据库吧」
--
-- ## 根因是喂给模型的清单是**平铺的名字**
--
-- 原来 appendContext 输出的是：
--     - 数据库
--     - 持久化
--     - Mybatis
--     - Lombok
-- 模型完全看不出它们有父子关系——以为「数据库」和「Mybatis」是并列的。
-- 后果实测两个：把一条知识分到 `Mybatis`（实际在「数据库/持久化」下**第三层**），
-- 以及把新提议的 `MySQL` 建到了顶层。
--
-- ## 三处改动
--
-- 1. **清单改成缩进树**（`AiChatServiceImpl.categoryTree`）。缩进就是层级。
--    父节点不在清单里时照样打印但当顶层 + `log.warn`——都是自己的数据，
--    真出现这种行说明有脏数据，**让它可见比让它凭空消失好**。
--    按 id 排序输出稳定，不然每次调用的清单顺序可能都不一样，模型没法比对。
--    `MAX_TREE_DEPTH = 10` 收住父子成环（目录可以自己新增、自己拖，环是可能的）。
--
-- 2. **输出改成路径**：`数据库/MySQL`。斜杠左边是上级、右边是这一条要归的目录。
--    提示词明确要求：要新建就写路径，别一律丢在顶层。
--
-- 3. **解析器认路径**（`aiAdopt.js` 的 `matchCategory`）：
--      完整路径命中 → 直接用（不同父目录下允许同名，只有路径能定死是哪一个）
--      只给名字   → 当相对路径按名字找，重名取第一个
--      父段在、末段不在 → 这就是"建议新建"，带上父级 id
--      **父段对不上 → 返回解析失败，不是"建在顶层"**
--         建在顶层是**猜**：用户以为它挂在「数据库」下，结果挂在根上，
--         而且界面上看不出来。宁可这一条不采纳。
--
-- 界面那边：已有目录的选项显示完整路径（`数据库/持久化/Mybatis`），
-- 新建项显示「+ 新建「MySQL」，放在「数据库」下」。批量采纳时**按「名字+父级」去重**
-- ——唯一键就是 (user_id, parent_id, name)，`数据库/JDBC` 和 `中间件/JDBC`
-- 是两个不同的目录，都要建。
--
-- ## 顺带收拾两个已经建错的目录
--
-- id=42 的名字是模型把理由一起吐出来了：
--     JDBC（清单里没有近义项，建议新增；退一步可归「数据库」）
-- `createCategory` 照单全收。**改名 + 归位**到「数据库」下。
-- id=41 `MySQL` 同样是上一轮建在顶层的，一起挪到「数据库」下。
--
-- 提示词侧的堵法在 `2026-10-07_no_reason_in_category_name.sql`（"只输出路径本身"）。
--
-- ⚠️ 这两条是**一次性数据修正**，不是迁移：下次跑 AI 归类不会再造出这种脏名字
-- （提示词已经堵了）。留着是为了说明"那两个目录当初是怎么错的"。
-- ============================================================

UPDATE `kp_category`
SET `name` = 'JDBC', `parent_id` = 28
WHERE `id` = 42 AND `name` LIKE 'JDBC（%';

UPDATE `kp_category`
SET `parent_id` = 28
WHERE `id` = 41 AND `name` = 'MySQL' AND `parent_id` = 0;


