/**
 * 掌握度档位的**展示映射**（前端唯一一份）。
 *
 * ## 为什么收在这里
 * 卡片右上角的轻签（`MasteryChip`）和书页顶部的分布概览（`MasteryOverview`）
 * 回答的是同一件事：「这个档位显示什么词、配什么颜色」—— 原来两个文件各写一份表，
 * `MasteryOverview` 的注释自己都写着「两处各写一份色值就会漂」（卡片上「待巩固」
 * 是黄的、概览里却是别的色，看着像两个东西）⇒ 收到这里一份。
 *
 * ⚠️ **档位词是后端算好下发的**（`MasteryCalculator`），**阈值判定只有后端那一份**，
 * 这里只管展示层：长词换短词、档位配语气色。**认不出的档位原样显示**（不猜、不兜底）。
 *
 * ⚠️ **档位色 = 三色相固定色，不跟主题**（2026-11-14 用户放开约束后定的终版）：
 * 琥珀黄（待巩固，全系统唯一的暖色 = 行动信号「要补」）/ 蓝（基本掌握 = 良好）/
 * 绿（熟练 & 稳定掌握 = 达成）。**顶档不单独配色**——档位高低由进度条（25/50/75/100）
 * 和词表达，颜色只负责「一眼扫描」：黄点在喊话，蓝绿点是没事了。
 * 四色相方案（含深绿/紫顶档）被否：5px 圆点撑不起色相内深浅判别，且与条/词重复编码。
 * ⚠️ **不要用红色**：红色语义是出错 / 要删（全站统一，见 base.css），掌握度低不是错误。
 * ⚠️ 灰系留给状态（未评估 = 不画、待复测 = 灰），彩色留给档位。
 */

/**
 * 概览条从左到右的**固定顺序**：低 → 高（词序 = 程度递进，档位与进度条永不倒挂）。
 */
export const LEVEL_ORDER = ['待巩固', '基本掌握', '熟练', '稳定掌握']

/**
 * 档位 → 展示三件套 + 进度：
 * - `word`：**短词**（卡片角标位只有几十像素宽，四字标签会把标题挤下去；长词留给详情页那套完整信息）
 * - `color`：**固定色**（不跟主题，见上；卡片签/树行圆点/树行条/概览全走这一份）
 * - `progress`：进度条填充（**档位段**，2026-11-14 用户拍板：最高档才是 100%；
 *   四档 = 25 / 50 / 75 / 100——条是档位的可视化，不再画原始 M 百分比）
 */
export const LEVEL_STYLE = {
  待巩固: { word: '待巩固', color: '#d9a441', progress: 25 },
  待复测: { word: '待复测', color: 'var(--cc-text-3)', progress: 25 },
  基本掌握: { word: '掌握', color: '#4a7fe0', progress: 50 },
  熟练: { word: '熟练', color: '#3fa66a', progress: 75 },
  稳定掌握: { word: '稳定', color: '#3fa66a', progress: 100 }
}

/** 某个档位的短词。认不出给原文 —— 不猜、不兜底成别的档。 */
export function levelWord(level) {
  return LEVEL_STYLE[level]?.word || level
}

/** 某个档位的颜色（卡片签/树行圆点/树行条/概览全走这里）。认不出的给中性灰。 */
export function levelColor(level) {
  return LEVEL_STYLE[level]?.color || 'var(--cc-text-3)'
}

/** 某个档位的进度条填充（档位段：25/50/75/100，最高档才是满）。认不出给 25。 */
export function levelProgress(level) {
  return LEVEL_STYLE[level]?.progress ?? 25
}
